// Package header holds the header of a synced file: its two lines, and the
// detection of a header in a file. It replaces _SE_HEADER_RE, _se_has_header,
// _SE_HEADER_LINE1 and _SE_HEADER_LINE2 of the bash file common.
//
// Contract: docs/design/cli.md ("The header").
package header

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"regexp"
)

// Line1Format is line 1 of the header, as a fmt format. The %s is the path of
// the source in bootstrap. A writer adds its comment marker.
const Line1Format = "Synced from bootstrap: %s. Do not edit this file."

// Line2 is line 2 of the header. A writer adds its comment marker.
const Line2 = "The next sync writes it again, and each change in this file is lost."

// Shared gives the lines of the header of a shared file: <source> is the path
// of its spec in bootstrap, <values> the values file of the side. A writer
// adds its comment marker.
func Shared(source, values string) []string {
	return []string{
		"Shared with bootstrap: " + source + ".",
		"A change in this file stays. A removed bootstrap item comes back at the next",
		"sync, unless " + values + " has an override for it.",
	}
}

// Line1 gives line 1 of the header for the source <source>, the path in
// bootstrap.
func Line1(source string) string { return fmt.Sprintf(Line1Format, source) }

// re is a comment line that starts with a header text. The old texts are for
// older copies: `repo-config` is the old name of bootstrap, and `Generated by
// macos-setup` is the header of the old Mac sync.
var re = regexp.MustCompile(`^[ \t\n\v\f\r]*(#|//|<!--)[ \t\n\v\f\r]*(Synced from (bootstrap|repo-config): |Generated by macos-setup)`)

// openComment is a line with only `<!--`: it opens a comment for the next line.
var openComment = regexp.MustCompile(`^[ \t\n\v\f\r]*<!--[ \t\n\v\f\r]*$`)

// Has reports whether one of the first 3 lines of <content> is a header line.
// A `<!--` line alone joins the next line, as in Markdown.
func Has(content []byte) bool {
	var lines [][]byte
	for len(lines) < 3 && len(content) > 0 {
		i := bytes.IndexByte(content, '\n')
		if i < 0 {
			lines = append(lines, content)
			break
		}
		lines = append(lines, content[:i])
		content = content[i+1:]
	}
	for i := 0; i < len(lines); i++ {
		line := lines[i]
		if openComment.Match(line) && i+1 < len(lines) {
			line = append(append(append([]byte{}, line...), ' '), lines[i+1]...)
			i++
		}
		if re.Match(line) {
			return true
		}
	}
	return false
}

// HasFile reports whether <path> is a regular file (after symlinks) with a
// header line in its first 3 lines.
func HasFile(path string) bool {
	info, err := os.Stat(path)
	if err != nil || !info.Mode().IsRegular() {
		return false
	}
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	var buf bytes.Buffer
	r := bufio.NewReader(f)
	for n := 0; n < 3; n++ {
		line, err := r.ReadBytes('\n')
		buf.Write(line)
		if err != nil {
			break
		}
	}
	return Has(buf.Bytes())
}
