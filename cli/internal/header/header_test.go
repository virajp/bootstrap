package header

import "testing"

// More cases of HasFile are in the tests of internal/manifest (case
// "header").
func TestHas(t *testing.T) {
	cases := []struct {
		in   string
		want bool
	}{
		{"# " + Line1("repo/tools/x/f") + "\n# " + Line2 + "\n", true},
		{"#!/bin/sh\n# Synced from bootstrap: x\n", true},
		{"a\nb\nc\n# Synced from bootstrap: x\n", false},
		{"<!--\nSynced from bootstrap: x\n-->\n", true},
		{"<!--\n<!--\n# Synced from bootstrap: x\n", true},
		{"a\nb\n<!--\nSynced from bootstrap: x\n", false},
		{"// Synced from repo-config: x", true},
		{"# Generated by macos-setup\n", true},
		{"# see Synced from bootstrap: x\n", false},
		{"", false},
	}
	for _, c := range cases {
		if got := Has([]byte(c.in)); got != c.want {
			t.Errorf("Has(%q) = %v, want %v", c.in, got, c.want)
		}
	}
	if got := Line1("a/b"); got != "Synced from bootstrap: a/b. Do not edit this file." {
		t.Errorf("Line1 = %q", got)
	}
}
