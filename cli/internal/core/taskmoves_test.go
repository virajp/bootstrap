// taskRepo is a repo fixture for init, with the task files <files> (path
// below the tasks folder to text).
func taskRepo(t *testing.T, files map[string]string) Side {
	t.Helper()
	sd := fixture(t, source.Repo, map[string]string{"a": "default_envs = [ \"dev\" ]\ndepends = []\nroot_only = false\n"},
		"[pack.base]\na = { required = true }\n", "")
	for rel, text := range files {
		p := filepath.Join(sd.Root, oldform.TasksDir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(text), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	return sd
}

// moveChanges gives the changes of <p> that move files.
func moveChanges(p *PlanResult) []oldform.Change {
	var out []oldform.Change
	for _, c := range p.Changes {
		if len(c.Moves) > 0 {
			out = append(out, c)
		}
	}
	return out
}

func TestPlanInitMovesOwnTests(t *testing.T) {
	// D7, D12 and D25: the own test/_default and test/e2e/_default move in
	// one change with the label, and its detail names each file.
	sd := taskRepo(t, map[string]string{"test/_default": "own\n", "test/e2e/_default": "e2e\n"})
	(&fakeSync{}).install(t, sd)
	p, err := Plan(sd, List{Init: true}, Options{})
	if err != nil {
		t.Fatal(problems(err))
	}
	mv := moveChanges(p)
	if len(mv) != 1 || len(mv[0].Moves) != 2 || !strings.HasPrefix(mv[0].Note, oldform.MoveNote+": ") ||
		!strings.Contains(mv[0].Note, "test/_default → ") || !strings.Contains(mv[0].Note, "test/e2e/50-local") {
		t.Fatalf("move changes %+v", mv)
	}
	// A repository without values is not adopted: sync does not migrate it.
	if need, err := MigrateNeeded(sd, true); need || err != nil {
		t.Errorf("MigrateNeeded = %v, %v", need, err)
	}
	if code, putBack, _, err := Apply(p, Options{}); code != fail.OK || putBack || err != nil {
		t.Fatalf("apply: %d %v %v", code, putBack, err)
	}
	tasks := filepath.Join(sd.Root, oldform.TasksDir)
	for p, want := range map[string]string{"test/50-local": "own\n", "test/e2e/50-local": "e2e\n"} {
		if b, _ := os.ReadFile(filepath.Join(tasks, p)); string(b) != want {
			t.Errorf("%s = %q, want %q", p, b, want)
		}
	}
	if Exists(filepath.Join(tasks, "test/_default")) {
		t.Error("test/_default is still there")
	}
}

func TestPlanInitMoveRestore(t *testing.T) {
	// A failed sync moves the own task back.
	sd := taskRepo(t, map[string]string{"test/_default": "own\n"})
	(&fakeSync{code: fail.Usage}).install(t, sd)
	p, err := Plan(sd, List{Init: true}, Options{})
	if err != nil {
		t.Fatal(problems(err))
	}
	if code, putBack, _, err := Apply(p, Options{}); code != fail.Usage || !putBack || err != nil {
		t.Fatalf("apply: %d %v %v", code, putBack, err)
	}
	tasks := filepath.Join(sd.Root, oldform.TasksDir)
	if b, _ := os.ReadFile(filepath.Join(tasks, "test/_default")); string(b) != "own\n" || Exists(filepath.Join(tasks, "test/50-local")) {
		t.Errorf("test/_default = %q", b)
	}
}

func TestPlanInitMoveTargetExists(t *testing.T) {
	// D8 and D20: a target exists: init stops with code 2 and moves nothing.
	sd := taskRepo(t, map[string]string{"test/_default": "own\n", "test/50-local": "part\n", "test/e2e": "e2e\n"})
	(&fakeSync{}).install(t, sd)
	_, err := Plan(sd, List{Init: true}, Options{})
	if fail.CodeOf(err) != fail.Usage || !strings.Contains(err.Error(), "test/50-local exists") {
		t.Fatalf("err = %v", err)
	}
	if !Exists(filepath.Join(sd.Root, oldform.TasksDir, "test/e2e")) {
		t.Error("test/e2e moved")
	}
}

func TestPlanInitKeepsSyncedTask(t *testing.T) {
	// D26: a test/_default with the header and no manifest entry is not
	// moved; the sync overwrites it. A listed one stays too.
	sd := taskRepo(t, map[string]string{"test/_default": "#!/bin/bash\n# Synced from bootstrap: repo/tools/x. Do not edit this file.\n"})
	(&fakeSync{}).install(t, sd)
	p, err := Plan(sd, List{Init: true}, Options{})
	if err != nil {
		t.Fatal(problems(err))
	}
	if mv := moveChanges(p); len(mv) != 0 {
		t.Errorf("move changes %+v", mv)
	}
	sd = taskRepo(t, map[string]string{"test/_default": "own\n"})
	m := filepath.Join(sd.Values, "repo-generated.tsv")
	if err := os.MkdirAll(sd.Values, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(m, []byte("mise\t"+oldform.TasksDir+"/test/_default\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	(&fakeSync{}).install(t, sd)
	if p, err = Plan(sd, List{Init: true}, Options{}); err != nil {
		t.Fatal(problems(err))
	}
	if mv := moveChanges(p); len(mv) != 0 {
		t.Errorf("listed: move changes %+v", mv)
	}
}
