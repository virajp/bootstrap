package manifest

import (
	"os"
	"path/filepath"
)

const hdr = "# Synced from bootstrap: x. Do not edit this file.\n"

func mkfile(root, rel, content string, mode os.FileMode) {
	p := filepath.Join(root, rel)
	os.MkdirAll(filepath.Dir(p), 0o777)
	os.WriteFile(p, []byte(content), mode)
	os.Chmod(p, mode)
}

func mklink(root, rel, to string) {
	p := filepath.Join(root, rel)
	os.MkdirAll(filepath.Dir(p), 0o777)
	os.Symlink(to, p)
}

func mkdir(root, rel string) { os.MkdirAll(filepath.Join(root, rel), 0o777) }

// both gives a real run and a dry run of the same case.
func both(name string, setup func(string), ops ...op) []pcase {
	return []pcase{
		{name: name, setup: setup, ops: ops},
		{name: name + "-dry", dry: true, setup: setup, ops: ops},
	}
}

const sha = "0123456789abcdef0123456789abcdef01234567"
const sha2 = "fedcba9876543210fedcba9876543210fedcba98"
const commentLine = "# The bootstrap commit of the last sync. repo-sync writes it."
const macHeader = "# The values of the Mac sync of bootstrap. See docs/setup/index.md."

func cases() []pcase {
	var cs []pcase
	add := func(list ...[]pcase) {
		for _, l := range list {
			cs = append(cs, l...)
		}
	}
	existing := func(content string, mode os.FileMode) func(string) {
		return func(r string) { mkfile(r, "d/f.txt", content, mode) }
	}

	// The write of one target.
	add(
		both("finish-new", nil, finish("644", "a\n", "new/dir/f.txt", "generated")),
		both("finish-new-exec", nil, finish("755", "#!/bin/sh\n", "t/task", "generated")),
		both("finish-changed", existing("old\nsame\n", 0o644), finish("644", "new\nsame\n", "d/f.txt", "generated")),
		both("finish-changed-no-newline", existing("a\nb", 0o644), finish("644", "a\nb\n", "d/f.txt", "generated")),
		both("finish-unchanged", existing("same\n", 0o644), finish("644", "same\n", "d/f.txt", "generated")),
		both("finish-mode", existing("same\n", 0o644), finish("755", "same\n", "d/f.txt", "generated")),
		both("finish-changed-and-mode", existing("old\n", 0o755), finish("644", "new\n", "d/f.txt", "generated")),
		both("finish-seed-new", nil, finish("644", "seed\n", "s/seed.yaml", "seed")),
		both("finish-merge-mode", existing("old\n", 0o600), finish("600", "new\n", "d/f.txt", "merge")),
		both("seed-kept", existing("mine\n", 0o644), seedKept("d/f.txt"), seedKept("d/none"),
			seedKept("d/dangling"), seedKept("d")),
		both("finish-dangling-link", func(r string) { mklink(r, "d/f.txt", "nowhere") },
			finish("644", "a\n", "d/f.txt", "generated")),
		both("finish-link-same", func(r string) {
			mkfile(r, "real.txt", "same\n", 0o644)
			mklink(r, "d/f.txt", "../real.txt")
		}, finish("644", "same\n", "d/f.txt", "generated")),
		both("finish-link-changed", func(r string) {
			mkfile(r, "real.txt", "old\n", 0o644)
			mklink(r, "d/f.txt", "../real.txt")
		}, finish("644", "new\n", "d/f.txt", "generated")),
		both("finish-dest-folder", func(r string) { mkdir(r, "d/f.txt") },
			finish("644", "a\n", "d/f.txt", "generated")),
		both("finish-many", existing("x\n", 0o644),
			finish("644", "x\n", "d/f.txt", "generated"),
			finish("644", "y\n", "d/g.txt", "generated"),
			finish("644", "z\n", "d/h.txt", "seed")),
	)

	// The unblock of a folder path.
	add(
		both("unblock-synced", func(r string) { mkfile(r, "code/format", hdr+"x\n", 0o755) },
			unblock("code/format", "", nil, ".config/x"),
			finish("755", "y\n", "code/format/_default", "generated")),
		both("unblock-deep", func(r string) { mkfile(r, "a", hdr, 0o644) },
			unblock("a/b/c", "", nil, "a/b/c/f")),
		both("unblock-not-synced", func(r string) { mkfile(r, "code/format", "mine\n", 0o644) },
			unblock("code/format", "", nil, "code/format/_default")),
		both("unblock-spare", func(r string) { mkfile(r, "code/format", hdr, 0o644) },
			unblock("code/format", "", []string{"other", "code/format"}, "code/format/_default")),
		both("unblock-link", func(r string) {
			mkfile(r, "real", hdr, 0o644)
			mklink(r, "code", "real")
		}, unblock("code/x", "", nil, "code/x/f")),
		both("unblock-none", func(r string) { mkdir(r, "a/b") }, unblock("a/b/c", "", nil, "a/b/c/f")),
		both("unblock-at-root", func(r string) { mkfile(r, "home/top", hdr, 0o644) },
			unblock("home", "home", nil, "home/f")),
		both("unblock-twice", func(r string) { mkfile(r, "a", hdr, 0o644) },
			unblock("a", "", nil, "a/f"), unblock("a", "", nil, "a/g")),
	)

	// The parse check and the merge: a failure keeps the existing file.
	add(
		both("check-json-bad", existing("{\"a\": 1}\n", 0o644),
			write("644", "{bad", "d/f.json", "generated", true, "", false)),
		both("check-json-new-bad", nil, write("644", "{bad", "d/f.json", "generated", true, "", false)),
		both("check-json-empty", nil, write("644", " \n", "d/f.json", "generated", true, "", false)),
		both("check-json-ok", existing("{\"a\": 1}\n", 0o644),
			write("644", "{\"a\": 2}\n", "d/f.json", "generated", true, "", false)),
		both("check-jsonc", nil, write("644", "// c\n{bad", "d/f.json", "generated", true, "", false)),
		both("check-jsonc-merge", nil, write("644", "// c\n{}", "d/f.json", "merge", true, "", true)),
		both("check-yaml-bad", existing("a: 1\n", 0o644),
			write("644", "a: [\n", "d/f.yaml", "generated", true, "", false)),
		both("check-toml-bad", existing("a = 1\n", 0o644),
			write("644", "a = \n", "d/f.toml", "generated", true, "", false)),
		both("check-format-key", nil, write("644", "a = [\n", "d/f.txt", "generated", true, "toml", false)),
		both("check-text", nil, write("644", "{bad", "d/f.txt", "generated", true, "", false)),
	)

	// The Mac side: a symlink in the path.
	macSetup := func(r string) {
		mkdir(r, "dotfiles/cfg")
		mklink(r, "home/.config", "../dotfiles/cfg")
		mklink(r, "home/loop", "loop2")
		mklink(r, "home/loop2", "loop")
	}
	add(
		both("macos-symlink-path", macSetup,
			realPath("home/.config/app/x.toml"), realPath("home/./a/../b"), realPath("home/loop/x"),
			writeReal("644", "a = 1\n", "home/.config/app/x.toml"),
			writeReal("644", "a\n", "home/loop/x")),
	)

	// The header.
	add(both("header", func(r string) {
		mkfile(r, "h1", hdr, 0o644)
		mkfile(r, "h2", "#!/bin/sh\n\n// Synced from bootstrap: x\n", 0o644)
		mkfile(r, "h3", "a\nb\nc\n# Synced from bootstrap: x\n", 0o644)
		mkfile(r, "h4", "<!--\nSynced from bootstrap: x\n-->\n", 0o644)
		mkfile(r, "h5", "  <!-- Synced from repo-config: x -->\n", 0o644)
		mkfile(r, "h6", "# Generated by macos-setup\n", 0o644)
		mkfile(r, "h7", "# see: Synced from bootstrap: x\n", 0o644)
		mkfile(r, "h8", "\t#\tSynced from bootstrap: x\r\n", 0o644)
		mkfile(r, "h9", "<!--\n<!--\n# Synced from bootstrap: x\n", 0o644)
		mkfile(r, "h10", "a\n<!--\nSynced from bootstrap: x\n", 0o644)
		mkfile(r, "h11", "# Synced from bootstrap: x", 0o644)
		mkfile(r, "h12", "", 0o644)
		mkdir(r, "h13")
		mklink(r, "h14", "h1")
		mklink(r, "h15", "none")
		mkfile(r, "h16", "#Synced from bootstrap:x\n", 0o644)
	}, hasHeader("h1"), hasHeader("h2"), hasHeader("h3"), hasHeader("h4"), hasHeader("h5"), hasHeader("h6"),
		hasHeader("h7"), hasHeader("h8"), hasHeader("h9"), hasHeader("h10"), hasHeader("h11"), hasHeader("h12"),
		hasHeader("h13"), hasHeader("h14"), hasHeader("h15"), hasHeader("h16"), hasHeader("none")))

	// The paths of a manifest row.
	var bp []op
	for _, p := range []string{"a", "a/b.txt", ".config/x", "", "/abs", "a//b", "a/", "./a", "a/./b", "a/..", "../a",
		".git", ".GIT/x", "a/.Git/b", ".gitignore", "a/.git2", "..a", "a.", "a b/c"} {
		bp = append(bp, badPath(p))
	}
	add(both("bad-path", nil, bp...))

	// The read of a manifest.
	const mf = ".config/repo-generated.tsv"
	rowsFile := FirstLine + "\n" +
		"git\t.config/mise/tasks/code/merge\n" +
		"\n" +
		"# a comment\n" +
		"no tab here\n" +
		"\tempty-tool\n" +
		"t\t/abs\n" +
		"t\ta/../b\n" +
		"t\t.git/hooks/h\n" +
		"t\tsub/.GIT/h\n" +
		"t\ta//b\n" +
		"t\ta\tb\n" +
		"t\tcr\r\n" +
		"t\t\n" +
		"last\tno-newline"
	add(
		both("read-repo", func(r string) { mkfile(r, mf, rowsFile, 0o644) }, read(Repo, mf, "")),
		both("read-repo-missing", nil, read(Repo, mf, "")),
		both("read-repo-link", func(r string) {
			mkfile(r, "outside.tsv", rowsFile, 0o644)
			mklink(r, mf, "../outside.tsv")
		}, read(Repo, mf, ""), read(Macos, mf, "")),
		both("read-repo-dangling", func(r string) { mklink(r, mf, "none") }, read(Repo, mf, ""), read(Macos, mf, "")),
		both("read-repo-below-link", func(r string) {
			mkfile(r, "out/repo-generated.tsv", rowsFile, 0o644)
			mklink(r, ".config", "out")
		}, read(Repo, mf, ""), read(Repo, mf, "/")),
		both("read-repo-folder", func(r string) { mkdir(r, mf) }, read(Repo, mf, ""), read(Macos, mf, "")),
		both("read-bad-mode", nil, read("nope", mf, "")),
		both("read-empty", func(r string) { mkfile(r, mf, "", 0o644) }, read(Repo, mf, "")),
	)

	// The stale rule.
	staleSetup := func(r string) {
		mkfile(r, "gone.txt", hdr, 0o644)
		mkfile(r, "a/b/c/deep.txt", hdr, 0o644)
		mkfile(r, "a/keep.txt", "x\n", 0o644)
		mkfile(r, "e/f/only.txt", hdr, 0o755)
		mkfile(r, "mine.txt", "no header\n", 0o644)
		mkfile(r, "handled.txt", hdr, 0o644)
		mkfile(r, "real.txt", hdr, 0o644)
		mklink(r, "link.txt", "real.txt")
		mkdir(r, "linkdir-real")
		mkfile(r, "linkdir-real/in.txt", hdr, 0o644)
		mklink(r, "linkdir", "linkdir-real")
		mkfile(r, "sub/stale.txt", hdr, 0o644)
		mkdir(r, "sub/.git")
		mkfile(r, "nested/x/stale.txt", hdr, 0o644)
		mkfile(r, "nested/.git", "gitdir: x\n", 0o644)
		mkfile(r, "hard-a.txt", hdr, 0o644)
		os.Link(filepath.Join(r, "hard-a.txt"), filepath.Join(r, "hard-b.txt"))
		mkdir(r, "folder.txt")
	}
	staleRows := []string{
		"t\tgone.txt", "t\ta/b/c/deep.txt", "t\te/f/only.txt", "t\tmine.txt", "t\thandled.txt",
		"t\tlink.txt", "t\tlinkdir/in.txt", "t\tsub/stale.txt", "t\tnested/x/stale.txt",
		"t\tnone.txt", "t\thard-b.txt", "t\tfolder.txt", "",
	}
	staleHandled := []string{"handled.txt", "hard-a.txt"}
	add(
		both("stale-repo", staleSetup, stale(Repo, staleRows, staleHandled, "")),
		both("stale-macos", staleSetup, stale(Macos, staleRows, staleHandled, "")),
		both("stale-macos-link", func(r string) {
			mkdir(r, "home/.config")
			mkfile(r, "dotfiles/mise/conf.d/old/mise.toml", hdr, 0o644)
			mklink(r, "home/.config/mise", "../../dotfiles/mise")
			mklink(r, "home/loop", "loop")
		}, stale(Macos, []string{"old\t.config/mise/conf.d/old/mise.toml", "x\tloop/y"}, nil, "home/"),
			stale(Repo, []string{"old\t.config/mise/conf.d/old/mise.toml"}, nil, "home")),
		both("stale-bad-mode", nil, stale("nope", []string{"t\ta"}, nil, "")),
		both("stale-remove-fails", func(r string) {
			mkfile(r, "ro/stale.txt", hdr, 0o644)
			mkfile(r, "ok.txt", hdr, 0o644)
			os.Chmod(filepath.Join(r, "ro"), 0o555)
		}, stale(Repo, []string{"t\tro/stale.txt", "t\tok.txt", "t\tro/stale.txt"}, nil, "")),
		both("prune", func(r string) {
			mkdir(r, "a/b/c")
			mkdir(r, "x/y")
			mkfile(r, "x/keep", "", 0o644)
			mkdir(r, "l-real/z")
			mklink(r, "l", "l-real")
		}, prune("", "a/b/c/f"), prune("", "x/y/f"), prune("", "l/z/f"), prune("a", "f")),
	)

	// The write of a manifest.
	add(
		both("write-new", nil, writeManifest(mf, []string{"b\tz", "a\ty", "", "b\tz", "a\tY", "a\t.x"})),
		both("write-empty", nil, writeManifest(mf, nil)),
		both("write-same", func(r string) { mkfile(r, mf, FirstLine+"\na\ty\n", 0o600) },
			writeManifest(mf, []string{"a\ty"})),
		both("write-changed", func(r string) { mkfile(r, mf, FirstLine+"\na\ty\n", 0o600) },
			writeManifest(mf, []string{"a\ty", "c\tz"})),
		both("write-crlf", func(r string) { mkfile(r, mf, FirstLine+"\r\na\ty\r\n", 0o644) },
			writeManifest(mf, []string{"a\ty"})),
		both("write-link", func(r string) {
			mkfile(r, "out.tsv", "x\n", 0o644)
			mklink(r, mf, "../out.tsv")
		}, writeManifest(mf, []string{"a\ty"})),
		both("write-blocked", func(r string) { mkfile(r, ".config", "file\n", 0o644) },
			writeManifest(mf, []string{"a\ty"})),
	)

	// bootstrap_commit.
	const vf = ".config/bootstrap.toml"
	add(
		both("commit-set", func(r string) {
			mkfile(r, vf, "# Synced values\n# more\n\nenvironments = [\"dev\"]\n\n[tools.x]\na = 1\n", 0o640)
		}, commit(vf, "bootstrap_commit", sha, commentLine, "")),
		both("commit-unchanged", func(r string) {
			mkfile(r, vf, "a = 1\nbootstrap_commit = \""+sha+"\"\n[t]\n", 0o644)
		}, commit(vf, "bootstrap_commit", sha, commentLine, "")),
		both("commit-replace", func(r string) {
			mkfile(r, vf, "# h\n\n# c\nbootstrap_commit = \""+sha2+"\"\na = 1\n[t]\nbootstrap_commit = \"x\"\n", 0o644)
		}, commit(vf, "bootstrap_commit", sha, commentLine, "")),
		both("commit-empty-value", func(r string) {
			mkfile(r, vf, "bootstrap_commit = \"\"\n", 0o644)
		}, commit(vf, "bootstrap_commit", sha, commentLine, "")),
		both("commit-in-table-only", func(r string) {
			mkfile(r, vf, "[t]\nbootstrap_commit = \""+sha+"\"\n", 0o644)
		}, commit(vf, "bootstrap_commit", sha, commentLine, "")),
		both("commit-header-no-blank", func(r string) {
			mkfile(r, vf, "# h1\n# h2\na = 1\n", 0o644)
		}, commit(vf, "bootstrap_commit", sha, commentLine, "")),
		both("commit-header-blank-last", func(r string) {
			mkfile(r, vf, "# h1\n\n", 0o644)
		}, commit(vf, "bootstrap_commit", sha, "", "")),
		both("commit-empty-file", func(r string) { mkfile(r, vf, "", 0o644) },
			commit(vf, "bootstrap_commit", sha, commentLine, "")),
		both("commit-no-newline", func(r string) { mkfile(r, vf, "a = 1", 0o644) },
			commit(vf, "bootstrap_commit", sha, commentLine, "")),
		both("commit-crlf", func(r string) {
			mkfile(r, vf, "# h\r\n\r\nbootstrap_commit = \""+sha+"\"\r\na = 1\r\n", 0o644)
		}, commit(vf, "bootstrap_commit", sha, commentLine, "")),
		both("commit-missing-no-header", nil, commit(vf, "bootstrap_commit", sha, commentLine, "")),
		both("commit-missing-header", func(r string) { mkdir(r, ".config") },
			commit(vf, "bootstrap_commit", sha, "", macHeader)),
		both("commit-missing-folder", nil, commit(vf, "bootstrap_commit", sha, "", macHeader)),
		both("commit-link", func(r string) {
			mkfile(r, "dot/macos.toml", "a = 1\n", 0o600)
			mklink(r, "cfg/macos.toml", "../dot/macos.toml")
		}, commit("cfg/macos.toml", "bootstrap_commit", sha, "", macHeader)),
		both("commit-link-chain", func(r string) {
			mkfile(r, "dot/macos.toml", "a = 1\n", 0o644)
			mklink(r, "cfg/l1", "../dot/macos.toml")
			mklink(r, "cfg/macos.toml", "l1")
		}, commit("cfg/macos.toml", "bootstrap_commit", sha, "", macHeader)),
		both("commit-dangling", func(r string) { mklink(r, "cfg/macos.toml", "../dot/new.toml"); mkdir(r, "dot") },
			commit("cfg/macos.toml", "bootstrap_commit", sha, "", macHeader)),
		both("commit-loop", func(r string) { mklink(r, "cfg/macos.toml", "macos.toml") },
			commit("cfg/macos.toml", "bootstrap_commit", sha, "", macHeader)),
		both("commit-short", func(r string) { mkfile(r, vf, "", 0o644) },
			commit(vf, "bootstrap_commit", "abc", "", "")),
	)
	return cs
}
