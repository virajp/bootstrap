// taskFile writes the task file <rel> below the tasks folder of <root>.
func taskFile(t *testing.T, root, rel, text string, mode os.FileMode) string {
	t.Helper()
	p := filepath.Join(root, TasksDir, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(text), mode); err != nil {
		t.Fatal(err)
	}
	return p
}

func show(p string) string { return p }

func TestPlanMovesStrayFile(t *testing.T) {
	// D4: a stray test/e2e file moves to test/e2e/50-local.
	root := t.TempDir()
	taskFile(t, root, "test/e2e", "#!/bin/bash\n", 0o755)
	moves, err := PlanMoves(root, nil, show)
	if err != nil {
		t.Fatal(err)
	}
	want := []Move{{root + "/" + TasksDir + "/test/e2e", root + "/" + TasksDir + "/test/e2e/50-local"}}
	if !reflect.DeepEqual(moves, want) {
		t.Fatalf("moves %v, want %v", moves, want)
	}
	if err := ApplyMoves(moves); err != nil {
		t.Fatal(err)
	}
	info, err := os.Stat(want[0].To)
	if err != nil || info.Mode().Perm() != 0o755 {
		t.Fatalf("moved file: %v %v", info, err)
	}
}

func TestPlanMovesOwnDefault(t *testing.T) {
	// D7 and D12: a repo's own test/_default and test/golden/_default move.
	root := t.TempDir()
	taskFile(t, root, "test/_default", "#!/bin/bash\n#MISE depends=[\"test:go\"]\n", 0o755)
	taskFile(t, root, "test/golden/_default", "#!/bin/bash\n", 0o755)
	moves, err := PlanMoves(root, nil, show)
	if err != nil {
		t.Fatal(err)
	}
	if len(moves) != 2 || !strings.HasSuffix(moves[0].To, "/test/50-local") || !strings.HasSuffix(moves[1].To, "/test/golden/50-local") {
		t.Fatalf("moves %v", moves)
	}
	if err := ApplyMoves(moves); err != nil {
		t.Fatal(err)
	}
	if isFile(moves[0].From) || !isFile(moves[0].To) || !isFile(moves[1].To) {
		t.Errorf("not moved: %v", moves)
	}
}

func TestPlanMovesListedOrSynced(t *testing.T) {
	root := t.TempDir()
	// A test/_default that the manifest lists is bootstrap's own.
	taskFile(t, root, "test/_default", "#!/bin/bash\n", 0o755)
	// D26: a file with the header and no manifest entry is bootstrap's own.
	taskFile(t, root, "test/e2e/_default", "#!/bin/bash\n# Synced from bootstrap: repo/tools/x. Do not edit this file.\n", 0o755)
	listed := Listed([]byte("# Written by bootstrap. Do not edit this file.\nmise\t" + TasksDir + "/test/_default\n"))
	moves, err := PlanMoves(root, listed, show)
	if err != nil || len(moves) != 0 {
		t.Errorf("moves %v, err %v", moves, err)
	}
	if err := TaskProblems(root, writeManifest(t, root, "mise\t"+TasksDir+"/test/_default\n"), show); err != nil {
		t.Errorf("problems: %v", err)
	}
}

func TestPlanMovesTargetExists(t *testing.T) {
	// D8 and D20: one target exists while another entry is due: code 2,
	// both paths named, and no move.
	root := t.TempDir()
	taskFile(t, root, "test/_default", "#!/bin/bash\n", 0o755)
	taskFile(t, root, "test/50-local", "#!/bin/bash\n", 0o755)
	golden := taskFile(t, root, "test/golden/_default", "#!/bin/bash\n", 0o755)
	moves, err := PlanMoves(root, nil, show)
	if fail.CodeOf(err) != fail.Usage || moves != nil {
		t.Fatalf("moves %v, err %v", moves, err)
	}
	msg := err.Error()
	if !strings.Contains(msg, TasksDir+"/test/_default") || !strings.Contains(msg, TasksDir+"/test/50-local") || strings.Contains(msg, "golden") {
		t.Errorf("message %q", msg)
	}
	if !isFile(golden) || !isFile(filepath.Join(root, TasksDir, "test/_default")) {
		t.Error("a file moved")
	}
}

func TestTaskProblems(t *testing.T) {
	// D4: check and sync give code 2 with the fix of init.
	root := t.TempDir()
	taskFile(t, root, "test", "#!/bin/bash\n", 0o755)
	err := TaskProblems(root, filepath.Join(root, "missing.tsv"), show)
	if fail.CodeOf(err) != fail.Usage || !strings.Contains(err.Error(), TasksDir+"/test is a task of this repo") || !strings.HasSuffix(err.Error(), "- "+Hint) {
		t.Errorf("err %v", err)
	}
	Migrating = true
	defer func() { Migrating = false }()
	if err := TaskProblems(root, filepath.Join(root, "missing.tsv"), show); err != nil {
		t.Errorf("while init plans: %v", err)
	}
}

func TestMovesFileToFolderAndBack(t *testing.T) {
	// The file test becomes test/50-local; the undo of a failed sync puts it
	// back, also after the sync wrote the folder test/.
	root := t.TempDir()
	from := taskFile(t, root, "test", "own\n", 0o755)
	moves, err := PlanMoves(root, nil, show)
	if err != nil {
		t.Fatal(err)
	}
	if err := ApplyMoves(moves); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(from + "/50-local"); string(b) != "own\n" {
		t.Fatalf("50-local = %q", b)
	}
	taskFile(t, root, "test/_default", "dispatcher\n", 0o755)
	if err := UndoMoves(moves); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(from); string(b) != "own\n" {
		t.Errorf("test = %q", b)
	}
}

func TestUnnamedParts(t *testing.T) {
	root := t.TempDir()
	// D15: an executable part without an NN- name.
	taskFile(t, root, "code/lint/mylint", "#!/bin/bash\n", 0o755)
	taskFile(t, root, "code/lint/05-linter", "#!/bin/bash\n", 0o755)
	taskFile(t, root, "code/lint/_default", "#!/bin/bash\n", 0o755)
	taskFile(t, root, "code/lint/notes", "text\n", 0o644)
	// D18: test/go is named by the depends of test/50-local.
	taskFile(t, root, "test/50-local", "#!/bin/bash\n#MISE depends=[\"test:repo\", \"test:go\"]\n", 0o755)
	taskFile(t, root, "test/go", "#!/bin/bash\n", 0o755)
	taskFile(t, root, "test/repo", "#!/bin/bash\n", 0o755)
	taskFile(t, root, "test/other", "#!/bin/bash\n", 0o755)
	want := []string{TasksDir + "/code/lint/mylint", TasksDir + "/test/other"}
	if got := UnnamedParts(root); !reflect.DeepEqual(got, want) {
		t.Errorf("unnamed %v, want %v", got, want)
	}
}

func writeManifest(t *testing.T, root, rows string) string {
	t.Helper()
	p := filepath.Join(root, "manifest.tsv")
	if err := os.WriteFile(p, []byte("# Written by bootstrap. Do not edit this file.\n"+rows), 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}
