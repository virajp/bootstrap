func TestManifestTextRefused(t *testing.T) {
	// A FIFO, a link or a file below a linked folder is not read, so a FIFO
	// does not block the sync before its manifest refusal; a regular file is
	// read.
	root := t.TempDir()
	dir := filepath.Join(root, ".config", "bootstrap")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	fifo := filepath.Join(dir, "fifo.tsv")
	if err := syscall.Mkfifo(fifo, 0o644); err != nil {
		t.Fatal(err)
	}
	regular := filepath.Join(dir, "repo-generated.tsv")
	if err := os.WriteFile(regular, []byte("mise\t"+TasksDir+"/test\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	link := filepath.Join(dir, "link.tsv")
	if err := os.Symlink(regular, link); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(dir, filepath.Join(root, "linked")); err != nil {
		t.Fatal(err)
	}
	type got struct {
		text   []byte
		exists bool
	}
	done := make(chan got, 1)
	go func() { b, ok := ManifestText(root, fifo); done <- got{b, ok} }()
	select {
	case g := <-done:
		if g.text != nil || !g.exists {
			t.Errorf("fifo: %q %v", g.text, g.exists)
		}
	case <-time.After(5 * time.Second):
		t.Fatal("the read of a FIFO manifest blocks")
	}
	for _, p := range []string{link, filepath.Join(root, "linked", "repo-generated.tsv")} {
		if b, ok := ManifestText(root, p); b != nil || !ok {
			t.Errorf("%s: %q %v", p, b, ok)
		}
	}
	if b, ok := ManifestText(root, filepath.Join(dir, "missing.tsv")); b != nil || ok {
		t.Errorf("missing: %q %v", b, ok)
	}
	if !ListedFile(root, regular)[TasksDir+"/test"] {
		t.Error("a regular manifest is not read")
	}
}

func TestMovesFileToFolderAndBack(t *testing.T) {
	// The file test becomes test/50-local; the undo of a failed sync puts it
	// back, also after the sync wrote the folder test/.
	root := t.TempDir()
	from := taskFile(t, root, "test", "own\n", 0o755)
	moves, err := PlanMoves(root, nil, show)
	if err != nil {
		t.Fatal(err)
	}
	if err := ApplyMoves(moves); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(from + "/50-local"); string(b) != "own\n" {
		t.Fatalf("50-local = %q", b)
	}
	taskFile(t, root, "test/_default", "dispatcher\n", 0o755)
	if err := UndoMoves(moves); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(from); string(b) != "own\n" {
		t.Errorf("test = %q", b)
	}
}

func TestOwnTasksLinked(t *testing.T) {
	// The engine follows no symlink: a tasks folder or a test folder that is a
	// link to a folder outside the repo, and a task file that is a link, give
	// no move and no problem, and the outside folder stays as it is.
	outside := t.TempDir()
	if err := os.WriteFile(filepath.Join(outside, "e2e"), []byte("own\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	// A tasks folder whose test folder is the outside folder.
	tasks := t.TempDir()
	if err := os.Symlink(outside, filepath.Join(tasks, "test")); err != nil {
		t.Fatal(err)
	}
	for linked, target := range map[string]string{TasksDir: tasks, TasksDir + "/test": outside} {
		root := t.TempDir()
		p := filepath.Join(root, linked)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.Symlink(target, p); err != nil {
			t.Fatal(err)
		}
		moves, err := PlanMoves(root, nil, show)
		if err != nil || len(moves) != 0 {
			t.Errorf("%s: moves %v, err %v", linked, moves, err)
		}
		if err := TaskProblems(root, filepath.Join(root, "missing.tsv"), show); err != nil {
			t.Errorf("%s: %v", linked, err)
		}
	}
	if b, err := os.ReadFile(filepath.Join(outside, "e2e")); err != nil || string(b) != "own\n" {
		t.Errorf("outside file: %q %v", b, err)
	}
	root := t.TempDir()
	real := taskFile(t, root, "real", "own\n", 0o755)
	if err := os.MkdirAll(filepath.Join(root, TasksDir, "test"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(real, filepath.Join(root, TasksDir, "test", "e2e")); err != nil {
		t.Fatal(err)
	}
	if got := OwnTasks(root, nil); len(got) != 0 {
		t.Errorf("a linked task file: %v", got)
	}
}

func TestPlanMovesTempNameExists(t *testing.T) {
	// A file at the temp name of a move gives code 2, and nothing moves.
	root := t.TempDir()
	from := taskFile(t, root, "test/e2e", "own\n", 0o755)
	taskFile(t, root, "test/e2e.bootstrap-move", "keep\n", 0o644)
	moves, err := PlanMoves(root, nil, show)
	if moves != nil || fail.CodeOf(err) != fail.Usage || !strings.Contains(err.Error(), from+".bootstrap-move") {
		t.Fatalf("moves %v, err %v", moves, err)
	}
	// move and UndoMoves never replace a file at the temp name.
	m := []Move{{From: from, To: from + "/50-local"}}
	if err := ApplyMoves(m); err == nil {
		t.Fatal("ApplyMoves replaced the file at the temp name")
	}
	if b, _ := os.ReadFile(from); string(b) != "own\n" {
		t.Errorf("from = %q", b)
	}
	if b, _ := os.ReadFile(from + ".bootstrap-move"); string(b) != "keep\n" {
		t.Errorf("temp = %q", b)
	}
	undo := []Move{{From: filepath.Join(root, "gone"), To: from}}
	if err := os.WriteFile(filepath.Join(root, "gone.bootstrap-move"), []byte("keep\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := UndoMoves(undo); err == nil {
		t.Fatal("UndoMoves replaced the file at the temp name")
	}
	if b, _ := os.ReadFile(from); string(b) != "own\n" {
		t.Errorf("from after undo = %q", b)
	}
}

func TestUnnamedParts(t *testing.T) {
	root := t.TempDir()
	// D15: an executable part without an NN- name.
	taskFile(t, root, "code/lint/mylint", "#!/bin/bash\n", 0o755)
	taskFile(t, root, "code/lint/05-linter", "#!/bin/bash\n", 0o755)
	taskFile(t, root, "code/lint/_default", "#!/bin/bash\n", 0o755)
	taskFile(t, root, "code/lint/notes", "text\n", 0o644)
	// D18: test/go is named by the depends of test/50-local.
	taskFile(t, root, "test/50-local", "#!/bin/bash\n#MISE depends=[\"test:repo\", \"test:go\"]\n", 0o755)
	taskFile(t, root, "test/go", "#!/bin/bash\n", 0o755)
	taskFile(t, root, "test/repo", "#!/bin/bash\n", 0o755)
	taskFile(t, root, "test/other", "#!/bin/bash\n", 0o755)
	want := []string{TasksDir + "/code/lint/mylint", TasksDir + "/test/other"}
	if got := UnnamedParts(root); !reflect.DeepEqual(got, want) {
		t.Errorf("unnamed %v, want %v", got, want)
	}
}

func writeManifest(t *testing.T, root, rows string) string {
	t.Helper()
	p := filepath.Join(root, "manifest.tsv")
	if err := os.WriteFile(p, []byte("# Written by bootstrap. Do not edit this file.\n"+rows), 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}
