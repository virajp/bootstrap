// taskFile writes the task file <rel> below the tasks folder of <root>.
func taskFile(t *testing.T, root, rel, text string, mode os.FileMode) string {
	t.Helper()
	p := filepath.Join(root, TasksDir, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(text), mode); err != nil {
		t.Fatal(err)
	}
	return p
}

func show(p string) string { return p }

func TestPlanMovesStrayFile(t *testing.T) {
	// D4: a stray test/e2e file moves to test/e2e/50-local.
	root := t.TempDir()
	taskFile(t, root, "test/e2e", "#!/bin/bash\n", 0o755)
	moves, err := PlanMoves(root, nil, show)
	if err != nil {
		t.Fatal(err)
	}
	want := []Move{{root + "/" + TasksDir + "/test/e2e", root + "/" + TasksDir + "/test/e2e/50-local"}}
	if !reflect.DeepEqual(moves, want) {
		t.Fatalf("moves %v, want %v", moves, want)
	}
	if err := ApplyMoves(moves); err != nil {
		t.Fatal(err)
	}
	info, err := os.Stat(want[0].To)
	if err != nil || info.Mode().Perm() != 0o755 {
		t.Fatalf("moved file: %v %v", info, err)
	}
}

