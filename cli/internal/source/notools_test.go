// The grep rule: the engine code names no tool. Each folder of repo/tools/ and
// macos/tools/ is a tool. The test reads each string literal of each Go file
// of cli/ that is not a test (not the import paths). It fails when a
// word of a literal is the name of a tool, and the allow lists below do not
// let that word.
//
// The engine knows these tools by its frame: mise (it generates and writes the
// mise config, and runs mise x and mise bootstrap), git (the repository, the
// members and the clone) and bash (it runs each tool script with bash).
var frameTools = map[string]bool{"mise": true, "git": true, "bash": true}

// englishWords are tool names that are also English words in a message.
var englishWords = map[string]bool{"go": true, "tree": true}

// allowed holds the words that a file can use, by file. An empty list lets
// each word.
var allowed = map[string][]string{
	// The migration of the old form of a values file names the old tools and
	// keys.
	"internal/oldform/oldform.go": nil,
	// The header of the old Mac sync is "Generated by macos-setup".
	"internal/header/header.go": {"macos-setup"},
	// The clone URL and the mise backend of bootstrap.
	"internal/core/clone.go": {"github"},
	// The SSH command of git.
	"internal/core/git.go": {"ssh"},
	// The messages of the old keys extensions and precommit name the new
	// places of their values.
	"internal/source/check.go": {"vscode", "pre-commit"},
	// The folder of the engine code in a clone is cli/, also the name of a
	// Mac tool.
	"internal/source/source.go": {"cli"},
	// The message of the old list form of [tools] has an example tool.
	"internal/values/values.go": {"node"},
	// The JSON parser keeps the error text of jq, which the old code used.
	"internal/format/jsonparse.go": {"jq"},
	// The message of the mise check gives the install command of mise.
	"internal/macos/sys.go": {"curl"},
	// The package scan of mac detect runs the command of the App Store apps
	// and reads the prefix mas: of [mise.bootstrap.packages], the package
	// manager of mise that installs them.
	"internal/core/packages.go": {"mas"},
}

// lets tells whether the file <rel> can use the word <w>.
func lets(rel, w string) bool {
	if englishWords[w] {
		return true
	}
	list, has := allowed[rel]
	if !has {
		return false
	}
	if list == nil {
		return true
	}
	for _, x := range list {
		if x == w {
			return true
		}
	}
	return false
}

// wordRe finds the words of a literal. A tool name has letters, digits, "-"
// and "_".
var wordRe = regexp.MustCompile(`[A-Za-z0-9_][A-Za-z0-9_-]*`)

// toolNames gives the names of the tool folders of both sides.
func toolNames(t *testing.T, root string) map[string]bool {
	t.Helper()
	names := map[string]bool{}
	for _, side := range []string{"repo", "macos"} {
		entries, err := os.ReadDir(filepath.Join(root, side, "tools"))
		if err != nil {
			t.Fatal(err)
		}
		for _, e := range entries {
			if e.IsDir() && !frameTools[e.Name()] {
				names[e.Name()] = true
			}
		}
	}
	if len(names) == 0 {
		t.Fatal("found no tool folders")
	}
	return names
}

func TestEngineNamesNoTool(t *testing.T) {
	engine, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	names := toolNames(t, filepath.Dir(engine))
	var found []string
	err = filepath.WalkDir(engine, func(p string, e os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if e.IsDir() && e.Name() == "testdata" {
			return filepath.SkipDir
		}
		if e.IsDir() || !strings.HasSuffix(p, ".go") || strings.HasSuffix(p, "_test.go") {
			return nil
		}
		rel, _ := filepath.Rel(engine, p)
		rel = filepath.ToSlash(rel)
		fset := token.NewFileSet()
		f, err := parser.ParseFile(fset, p, nil, parser.SkipObjectResolution)
		if err != nil {
			return err
		}
		ast.Inspect(f, func(n ast.Node) bool {
			switch x := n.(type) {
			case *ast.ImportSpec:
				return false
			case *ast.BasicLit:
				if x.Kind != token.STRING {
					return true
				}
				text, err := strconv.Unquote(x.Value)
				if err != nil {
					text = x.Value
				}
				for _, w := range wordRe.FindAllString(text, -1) {
					if names[w] && !lets(rel, w) {
						found = append(found, fset.Position(x.Pos()).String()+": "+w)
					}
				}
			}
			return true
		})
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	sort.Strings(found)
	for _, f := range found {
		t.Errorf("the engine names the tool %s", strings.TrimPrefix(f, engine+"/"))
	}
}
