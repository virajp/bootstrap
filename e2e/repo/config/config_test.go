// consumerWithSubmodule: a git submodule `sub` in the consumer.
func consumerWithSubmodule(c *rc.Case) { addSubmodule(c, "sub") }

// subRepoName: the member names. A submodule without a table gets the
// repo_name of its own values file, else its path with each `/` changed to
// `_`.
func subRepoName(name string) func(c *rc.Case) {
	return func(c *rc.Case) {
		consumerWithSubmodule(c)
		mkdir(c, "sub/.config")
		mkdir(c, "projects/web")
		dir := c.Path("sub/.config/bootstrap")
		rc.WriteValues(c.T, dir, "")
		p := filepath.Join(dir, "repo.toml")
		re := regexp.MustCompile(`(?m)^repo_name = .*$`)
		harness.WriteFile(c.T, p, re.ReplaceAllLiteralString(harness.ReadFile(p), `repo_name = "`+name+`"`))
	}
}

