// realRun is the argument list of a case that syncs for real (case_args=' ').
var realRun = []string{}

// check runs one case with `bootstrap check` and no other argument. rc.Check
// alone keeps the default argument --dry-run of a sync, which `bootstrap check`
// refuses, so each check case gives an empty argument list.
func check(t *testing.T, s rc.Spec) {
	t.Helper()
	if s.Args == nil {
		s.Args = []string{}
	}
	rc.Check(t, s)
}

// write writes the lines <lines> to the file <rel> of the consumer.
func write(c *rc.Case, rel string, lines ...string) {
	harness.WriteFile(c.T, c.Path(rel), harness.Lines(lines...))
}

func mkdir(c *rc.Case, rel string) {
	if err := os.MkdirAll(c.Path(rel), 0o755); err != nil {
		c.T.Fatal(err)
	}
}

// manifestFile writes .config/bootstrap/repo-generated.tsv of the consumer,
// with the first line and the rows <rows>.
func manifestFile(c *rc.Case, rows ...string) {
	write(c, ".config/bootstrap/repo-generated.tsv", append([]string{"# Written by bootstrap. Do not edit this file."}, rows...)...)
}

// checkLogLacks records the check "<name>: no <text>": the output of the case
// must not have the fixed string <text>.
func checkLogLacks(c *rc.Case, name, text string) {
	c.T.Helper()
	if c.LogHas(text) {
		harness.Fail(c.T, name+": the output has: "+text, c.LogText())
	} else {
		c.Pass(name + ": no " + text)
	}
}

func lacks(name, text string) func(c *rc.Case) {
	return func(c *rc.Case) { checkLogLacks(c, name, text) }
}

// hasLine tells whether the file <path> has a line that is exactly <line>.
func hasLine(path, line string) bool {
	for _, l := range strings.Split(harness.ReadFile(path), "\n") {
		if l == line {
			return true
		}
	}
	return false
}

