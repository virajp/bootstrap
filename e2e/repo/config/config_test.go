// oldConfFile writes a generated mise file that no tool writes, with the text
// <lines>, listed in the manifest.
func oldConfFile(lines ...string) func(c *rc.Case) {
	return func(c *rc.Case) {
		write(c, oldConf, lines...)
		manifestFile(c, "oldtool\t"+oldConf)
	}
}

func checkOldConfRemoved(c *rc.Case) {
	if strings.Contains(c.LogText(), "would remove "+c.Consumer+"/"+oldConf) {
		c.Pass("the header on line 2: would remove")
	} else {
		c.Fail("the header on line 2: the output lacks would remove")
	}
}

func lacksOldConfRemove(name string) func(c *rc.Case) {
	return func(c *rc.Case) { checkLogLacks(c, name, "would remove "+c.Consumer+"/"+oldConf) }
}

// The header detection: a generated mise file with a header text on line 2,
// listed in the manifest. The stale removal reads 3 lines. A dry run names the
// file with its full path, and a case has its own consumer, so a check
// examines it.
func TestHeaderDetection(t *testing.T) {
	rc.Run(t, rc.Spec{Name: "the header on line 2: Synced from bootstrap", Values: devValues,
		Change: oldConfFile("# A plain comment.", "# Synced from bootstrap: tools/oldtool/tools.toml. Do not edit this file."),
		Check:  checkOldConfRemoved})
	rc.Run(t, rc.Spec{Name: "the header on line 2: Synced from repo-config", Values: devValues,
		Change: oldConfFile("# A plain comment.", "# Synced from repo-config: tools/oldtool/tools.toml. Do not edit this file."),
		Check:  checkOldConfRemoved})
	rc.Run(t, rc.Spec{Name: "the header on line 2: Generated by macos-setup", Values: devValues,
		Change: oldConfFile("# A plain comment.", "# Generated by macos-setup"), Check: checkOldConfRemoved})
	rc.Run(t, rc.Spec{Name: "a file without the header stays", Values: devValues,
		Change: oldConfFile("# A plain comment.", "# Written by this repo."), Check: lacksOldConfRemove("a file without the header stays")})
	rc.Run(t, rc.Spec{Name: "a comment that only mentions a header text stays", Values: devValues,
		Change: oldConfFile("# Hand-written. Not Generated by macos-setup, keep it."),
		Check:  lacksOldConfRemove("a comment that only mentions a header text stays")})
}
