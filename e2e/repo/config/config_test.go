// hookArgs gives the args of the no-commit-to-branch hook, on one line, or ""
// on an error.
func hookArgs(c *rc.Case) string {
	cmd := &harness.Cmd{Env: c.Env, Args: []string{"yq",
		`[.repos[].hooks[] | select(.id == "no-commit-to-branch") | .args[]] | join(" ")`,
		c.Path(".config/pre-commit-config.yaml")}}
	code, out := cmd.Run()
	if code != 0 {
		return ""
	}
	return strings.TrimRight(out, "\n")
}

func expectHook(name, want string) func(c *rc.Case) {
	return func(c *rc.Case) {
		c.T.Helper()
		if got := hookArgs(c); got == want {
			c.Pass(name + ": the hook args are '" + want + "'")
		} else {
			harness.Fail(c.T, name+": the hook args are '"+got+"', expected '"+want+"'", "")
		}
	}
}

var (
	hookBoth     = expectHook("the protected branches, no landing", "--branch main --branch develop")
	hookMainOnly = expectHook("the protected branches, main only, no landing", "--branch main")
	hookMain     = expectHook("the protected branches, develop direct-commit", "--branch main")
	hookNone     = expectHook("the protected branches, each one direct-commit", "")
)

func ownHookStays(c *rc.Case) {
	f := c.Path(".config/pre-commit-config.yaml")
	if rc.FileHas(f, "example.com/own-hooks") && hasLine(f, "own_key: 1") && hasLine(f, "# own comment") {
		c.Pass("the own hook block, key and comment stay")
	} else {
		harness.Fail(c.T, "the own hook block, key or comment is gone", harness.ReadFile(f))
	}
	hookMainOnly(c)
}

