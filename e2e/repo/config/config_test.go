// dropLines removes each line of the file <path> that starts with <prefix>.
func dropLines(c *rc.Case, path, prefix string) {
	var out []string
	for _, l := range strings.Split(harness.ReadFile(path), "\n") {
		if !strings.HasPrefix(l, prefix) {
			out = append(out, l)
		}
	}
	harness.WriteFile(c.T, path, strings.Join(out, "\n"))
}

