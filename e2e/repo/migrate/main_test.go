// writeLines writes <lines> to <path>, one line each (printf '%s\n').
func writeLines(c *rc.Case, path string, lines ...string) {
	harness.WriteFile(c.T, path, harness.Lines(lines...))
}

// appendLines appends <lines> to <path>, one line each.
func appendLines(c *rc.Case, path string, lines ...string) {
	harness.AppendFile(c.T, path, harness.Lines(lines...))
}

func mkdir(c *rc.Case, path string) {
	if err := os.MkdirAll(path, 0o755); err != nil {
		c.T.Fatal(err)
	}
}

// git runs git in the consumer of the case.
func git(c *rc.Case, args ...string) string { return harness.Git(c.T, c.Consumer, args...) }

// lineIn tells whether <path> has the line <line> (grep -qxF).
func lineIn(path, line string) bool {
	for _, l := range strings.Split(harness.ReadFile(path), "\n") {
		if l == line {
			return true
		}
	}
	return false
}

// reIn tells whether a line of <path> matches <re> (grep -qE).
func reIn(path, re string) bool {
	return regexp.MustCompile("(?m)" + re).MatchString(harness.ReadFile(path))
}

// notGrep tells whether no line of <path> matches <re> (not_grep).
func notGrep(path, re string) bool {
	return !reIn(path, re)
}

func exists(path string) bool { return !rc.NoFile(path) }

func isFile(path string) bool {
	fi, err := os.Stat(path)
	return err == nil && fi.Mode().IsRegular()
}

// logLine tells whether the output has the line <line> (log_line).
func logLine(c *rc.Case, line string) bool { return lineIn(c.Log, line) }

// lastLine gives the last line of the output (tail -n 1).
func lastLine(c *rc.Case) string {
	s := strings.TrimSuffix(c.LogText(), "\n")
	if i := strings.LastIndex(s, "\n"); i >= 0 {
		return s[i+1:]
	}
	return s
}

// checkLogLacks records the check "<name>: no <text>": the output does not
// have the fixed string <text> (check_log_lacks).
func checkLogLacks(c *rc.Case, name, text string) {
	c.T.Helper()
	if c.LogHas(text) {
		c.Fail(name + ": the output has: " + text)
		return
	}
	c.Pass(name + ": no " + text)
}

// checkExact records the check <name>: the file <path> holds <content>,
// byte for byte (check_exact).
func checkExact(c *rc.Case, name, path, content string) {
	c.T.Helper()
	b, err := os.ReadFile(path)
	if err == nil && string(b) == content {
		c.Pass(name)
		return
	}
	harness.Fail(c.T, name+": "+path+" changed", string(b))
}

// envAgain is the environment of a later run of the engine in the case:
// the environment of the case without FORCE_COLOR and BOOTSTRAP_URL.
func envAgain(c *rc.Case) []string {
	return harness.SetEnv(c.Env, "FORCE_COLOR", "BOOTSTRAP_URL",
		"BOOTSTRAP_VALUES="+c.Values, "MISE_PROJECT_ROOT="+c.Consumer,
		"BOOTSTRAP_CLONE="+c.Clone, "BOOTSTRAP_CACHE="+filepath.Join(c.Dir, "cache"))
}

// runToLog runs <args> with <env> in <dir> and writes the output to the log
// of the case, in place of the old output.
func runToLog(c *rc.Case, env []string, dir string, args ...string) int {
	f, err := os.Create(c.Log)
	if err != nil {
		c.T.Fatal(err)
	}
	defer func() { _ = f.Close() }()
	cmd := &harness.Cmd{Dir: dir, Env: env, Out: f, Args: args}
	code, _ := cmd.Run()
	return code
}

// caseEngine commits the consumer and runs the engine again in the case,
// with <env> (nil is envAgain). The log gets its output (case_engine and
// case_rerun).
func caseEngine(c *rc.Case, env []string, args ...string) int {
	if env == nil {
		env = envAgain(c)
	}
	c.CommitConsumer()
	return runToLog(c, env, "", append([]string{harness.Bin}, args...)...)
}

// consumerState gives the files of the consumer, without its .git, with a
// hash of each one (consumer_state).
func consumerState(c *rc.Case) string {
	var rows []string
	_ = filepath.WalkDir(c.Consumer, func(p string, e os.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if e.IsDir() && p == filepath.Join(c.Consumer, ".git") {
			return filepath.SkipDir
		}
		if e.Type().IsRegular() {
			b, _ := os.ReadFile(p)
			rows = append(rows, fmt.Sprintf("%s %x", p, sha256.Sum256(b)))
		}
		return nil
	})
	sort.Strings(rows)
	return strings.Join(rows, "\n")
}

