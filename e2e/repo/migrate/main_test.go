// consumerWithSubmodule adds a git submodule `sub` to the consumer.
func consumerWithSubmodule(c *rc.Case) {
	git(c, "-c", "protocol.file.allow=always", "submodule", "--quiet", "add", "--", rc.BaseClone, "sub")
}

// consumerSubmodule makes the consumer a git submodule: a gitlink at its
// path in a superproject at the folder of the case.
func consumerSubmodule(c *rc.Case) {
	harness.Git(c.T, c.Dir, "init", "--quiet")
	head := git(c, "rev-parse", "HEAD")
	harness.Git(c.T, c.Dir, "update-index", "--add", "--cacheinfo", "160000,"+head+",consumer")
}

