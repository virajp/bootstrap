// The default output. These cases run without BOOTSTRAP_VERBOSE and the
// style variables, and the output is a log file, not a terminal.

// outputRun gives the Call of a case of the default output: it removes the
// variables, sets <set>, and runs `bootstrap sync <args>`.
func outputRun(set []string, args ...string) func(c *rc.Case) int {
	return func(c *rc.Case) int {
		c.Env = harness.SetEnv(c.Env, "BOOTSTRAP_VERBOSE", "FORCE_COLOR", "NO_COLOR")
		c.Env = harness.SetEnv(c.Env, set...)
		return c.Engine(append([]string{"sync"}, args...)...)
	}
}

// rerun runs the engine again with `sync <args>` and the extra variables
// <set> (case_rerun).
func rerun(c *rc.Case, set []string, args ...string) int {
	env := harness.SetEnv(envAgain(c), set...)
	return caseEngine(c, env, append([]string{"sync"}, args...)...)
}

var (
	syncedRe = regexp.MustCompile(`^\[[A-Z]+\] (Synced|Dry run): ([0-9]+) files?.*`)
)

// countOf gives the count of the kind <label> in the last line of the plain
// output. The kind `changed` is the headline count minus the other kinds in
// it.
func countOf(c *rc.Case, label string) int {
	last := lastLine(c)
	if label == "changed" {
		n := 0
		if m := syncedRe.FindStringSubmatch(last); m != nil {
			n, _ = strconv.Atoi(m[2])
		}
		return n - countOf(c, "new") - countOf(c, "seeded") - countOf(c, "removed")
	}
	re := regexp.MustCompile(`^.* · ([0-9]+) ` + regexp.QuoteMeta(label) + `( .*)?$`)
	if m := re.FindStringSubmatch(last); m != nil {
		n, _ := strconv.Atoi(m[1])
		return n
	}
	return 0
}

func countIs(c *rc.Case, label string, n int) bool { return countOf(c, label) == n }

// noTable: the output has no table.
func noTable(c *rc.Case) bool {
	return !regexp.MustCompile(`(?m)^\| |^\+---`).MatchString(c.LogText())
}

// unchangedLines counts the lines of the verbose output for unchanged files.
func unchangedLines(c *rc.Case) int {
	n := 0
	for _, l := range strings.Split(c.LogText(), "\n") {
		if strings.HasPrefix(l, "bootstrap: unchanged  ") {
			n++
		}
	}
	return n
}

func lastMatches(c *rc.Case, re string) bool { return regexp.MustCompile(re).MatchString(lastLine(c)) }

// outputFiles: the tool fixture with three files that have the header.
func outputFiles(c *rc.Case) {
	fixtureTool(c)
	for _, name := range []string{"a", "b", "c"} {
		fixtureFile(c, name+".txt", append(fixtureHeader(name+".txt", "#"), name)...)
	}
}

func outputEditA(c *rc.Case) {
	writeLines(c, c.Path("a.txt"), "# Synced from bootstrap: repo/tools/fixture/a.txt. Do not edit this file.", "edited")
}

func checkOutputList(c *rc.Case) {
	cons := c.Consumer
	c.CheckThat("the default output: the first run lists a new file", logLine(c, "new "+cons+"/c.txt"))
	c.CheckThat("the default output: the first run has no table", noTable(c))
	// A second run writes the mise fragments and `_default` of the first run
	// again, so the third run is the one with exact counts.
	got := rerun(c, nil)
	c.CheckThat("the default output: the second run exits 0", got == 0)
	outputEditA(c)
	_ = os.Remove(c.Path("b.txt"))
	got = rerun(c, nil)
	c.CheckThat("the default output: exit 0", got == 0)
	c.CheckThat("the default output: a changed file", logLine(c, "changed "+cons+"/a.txt"))
	c.CheckThat("the default output: a new file", logLine(c, "new "+cons+"/b.txt"))
	c.CheckThat("the default output: no unchanged file", c.LogLacks(cons+"/c.txt"))
	c.CheckThat("the default output: Changed", countIs(c, "changed", 1))
	c.CheckThat("the default output: New", countIs(c, "new", 1))
	c.CheckThat("the default output: Seeded", countIs(c, "seeded", 0))
	c.CheckThat("the default output: Removed", countIs(c, "removed", 0))
	c.CheckThat("the default output: Failed", countIs(c, "failed", 0))
	c.CheckThat("the default output: no table", noTable(c))
	c.CheckThat("the default output: the last line",
		lastMatches(c, `^\[OK\] Synced: 2 files changed · 1 new( · [0-9]+ (unchanged|kept seeds|skipped))*$`))
	c.CheckThat("the default output: no per-file log line", c.LogLacks("unchanged  "))
	unchanged := countOf(c, "unchanged")
	got = rerun(c, []string{"BOOTSTRAP_VERBOSE=1"})
	c.CheckThat("verbose: exit 0", got == 0)
	c.CheckThat("verbose: each unchanged file, a.txt and b.txt too", unchangedLines(c) == unchanged+2)
	c.CheckThat("verbose: no table", noTable(c))
	c.CheckThat("verbose: the last line", lastMatches(c, `^\[OK\] Synced: no file changed( · .*)?$`))
	_ = rerun(c, []string{"BOOTSTRAP_VERBOSE=true"})
	c.CheckThat("only the value 1 is verbose", c.LogLacks("unchanged  "))
	got = rerun(c, nil, "--verbose")
	c.CheckThat("--verbose: exit 0", got == 0)
	c.CheckThat("--verbose: each unchanged file", unchangedLines(c) == unchanged+2)
	c.CheckThat("--verbose: the last line", lastMatches(c, `^\[OK\] Synced: no file changed( · .*)?$`))
}

func checkOutputSeed(c *rc.Case) {
	cons := c.Consumer
	c.CheckThat("the default output, a new seed: seeded", logLine(c, "seeded "+cons+"/a.txt"))
	seeds := countOf(c, "seeded")
	c.CheckThat("the default output, a new seed: counted", seeds >= 1)
	got := rerun(c, nil)
	c.CheckThat("the default output, an existing seed: exit 0", got == 0)
	c.CheckThat("the default output, an existing seed: not listed", c.LogLacks(cons+"/a.txt"))
	c.CheckThat("the default output, an existing seed: not seeded", countIs(c, "seeded", 0))
	c.CheckThat("the default output, an existing seed: Kept seeds", countIs(c, "kept seeds", seeds))
}

func checkOutputFailed(c *rc.Case) {
	cons := c.Consumer
	c.CheckThat("the default output, a failed file: the list",
		logLine(c, "failed "+cons+"/bad.json: the result does not parse as json - the current file stays"))
	c.CheckThat("the default output, a failed file: the good file", logLine(c, "new "+cons+"/good.txt"))
	c.CheckThat("the default output, a failed file: Failed", countIs(c, "failed", 1))
	c.CheckThat("the default output, a failed file: no count of files in sync", c.LogLacks("files in sync"))
	c.CheckThat("the default output, a failed file: the last line",
		lastMatches(c, `^\[ERROR\] The sync failed with code 2 · 1 failed( · .*)?$`))
}

func checkOutputPlain(c *rc.Case) {
	for _, text := range []string{"✎", "✚", "❋", "✖", "✗", "┌", "│", "↻", "✔", "▸", "\x1b"} {
		// The name is the old `printf '%q'` text of bash 3.2.
		name := text
		if text == "\x1b" {
			name = "$'\x1b'"
		}
		c.CheckThat("no terminal: no "+name, c.LogLacks(text))
	}
	c.CheckThat("no terminal: the info line", c.LogHas("[INFO] bootstrap "))
	c.CheckThat("no terminal: no table", noTable(c))
	c.CheckThat("no terminal: the last line", regexp.MustCompile(`(?m)^\[OK\] Synced: [0-9]+ files changed( · .*)?$`).MatchString(c.LogText()))
}

func checkOutputForced(c *rc.Case) {
	cons := c.Consumer
	c.CheckThat("FORCE_COLOR: a changed line", c.LogHas("✎ changed  "+cons+"/a.txt"))
	c.CheckThat("FORCE_COLOR: a new line", c.LogHas("✚ new      "+cons+"/b.txt"))
	c.CheckThat("FORCE_COLOR: the clone line", c.LogHas("↻ bootstrap "))
	c.CheckThat("FORCE_COLOR: no box table", c.LogLacks("┌"))
	c.CheckThat("FORCE_COLOR: the last line", c.LogHas("✔"))
	c.CheckThat("FORCE_COLOR: an escape code", c.LogHas("\x1b["))
	c.CheckThat("FORCE_COLOR: no plain info line", c.LogLacks("[INFO]"))
}

func TestDefaultOutput(t *testing.T) {
	rc.Run(t, rc.Spec{Name: "the default output: the list and the table", Values: fixtureValues,
		Change: outputFiles, Call: outputRun(nil), Check: checkOutputList})
	rc.Run(t, rc.Spec{Name: "the default output: a seed", Values: fixtureValues, Change: func(c *rc.Case) {
		fixtureTxt(c)
		fixtureToml(c, `[files."a.txt"]`, `mode = "seed"`)
	}, Call: outputRun(nil), Check: checkOutputSeed})
	rc.Run(t, rc.Spec{Name: "the default output: a failed file", Code: 2, Values: fixtureValues,
		Change: fixtureBadAndGood, Call: outputRun(nil), Message: "FAILED: ", Check: checkOutputFailed})

	var dryState string
	rc.Run(t, rc.Spec{Name: "the default output: a dry run", Values: fixtureValues, Change: func(c *rc.Case) {
		outputFiles(c)
		outputEditA(c)
		dryState = consumerState(c)
	}, Call: outputRun(nil, "--dry-run"), Check: func(c *rc.Case) {
		cons := c.Consumer
		c.CheckThat("the default dry run: would change", logLine(c, "would change "+cons+"/a.txt"))
		c.CheckThat("the default dry run: would add", logLine(c, "would add "+cons+"/b.txt"))
		c.CheckThat("the default dry run: the diff of a change", c.LogHas(cons+"/a.txt (bootstrap)"))
		c.CheckThat("the default dry run: Changed", countIs(c, "changed", 1))
		c.CheckThat("the default dry run: no table", noTable(c))
		c.CheckThat("the default dry run: the commit line", c.LogHas("[INFO] bootstrap_commit would change to "))
		c.CheckThat("the default dry run: the last line",
			regexp.MustCompile(`(?m)^\[OK\] Dry run: [0-9]+ files would change( · .*)?$`).MatchString(c.LogText()))
		c.CheckThat("the default dry run: writes nothing", consumerState(c) == dryState)
	}})

	rc.Run(t, rc.Spec{Name: "the default output: not a terminal", Values: fixtureValues,
		Change: outputFiles, Call: outputRun(nil), Check: checkOutputPlain})
	rc.Run(t, rc.Spec{Name: "the default output: FORCE_COLOR", Values: fixtureValues, Change: func(c *rc.Case) {
		outputFiles(c)
		outputEditA(c)
	}, Call: outputRun([]string{"FORCE_COLOR=1"}), Check: checkOutputForced})
}
