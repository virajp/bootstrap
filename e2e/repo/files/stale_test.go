const (
	manifestLinkMessage = "the manifest is a link or is below a linked folder - not read"
	manifestKindMessage = "the manifest is not a regular file - not read"
	memberMemValues     = `environments = [ "dev" ]
[members.mem]
type = "folder"`
)

// skippedRows records a check for each line of <lines>: the line of the
// manifest is skipped.
func skippedRows(c *rc.Case, prefix string, lines ...int) {
	for _, n := range lines {
		c.CheckThat(prefix+": line "+strconv.Itoa(n)+" is skipped",
			c.LogHas(manifestPath(c)+": line "+strconv.Itoa(n)+" is not <tool><TAB><path> - skipped"))
	}
}

// The manifest .config/bootstrap/repo-generated.tsv and the stale rule.
func TestStaleRule(t *testing.T) {
	// A first sync has no manifest and removes nothing.
	rc.Run(t, rc.Spec{Name: "the stale rule, no manifest", Values: noToolValues,
		Change: func(c *rc.Case) { headerFile(c, oldConf) },
		Check: func(c *rc.Case) {
			c.CheckThat("no manifest: no would remove", c.LogLacks("would remove"))
			c.CheckThat("no manifest: the file stays", isFile(c.Path(oldConf)))
		}})
	// A synced gate without a manifest stays: the condition only skips the
	// write.
	rc.Run(t, rc.Spec{Name: "[files], no pyproject.toml: a synced gate without a manifest stays", Values: pythonValues,
		Change: gateSyncedCopy,
		Check: func(c *rc.Case) {
			c.CheckThat("a synced gate, no manifest: skip file", c.LogHas("skip file  "+c.Path(gate)+" (no pyproject.toml)"))
			c.CheckThat("a synced gate, no manifest: no would remove", c.LogLacks("would remove"))
			c.CheckThat("a synced gate, no manifest: the file stays", isFile(c.Path(gate)))
		}})
	rc.Run(t, rc.Spec{Name: "the stale rule, a listed header file", Values: noToolValues,
		Change: func(c *rc.Case) {
			headerFile(c, oldConf)
			manifestFile(c, "oldtool"+tab+oldConf)
		},
		Check: func(c *rc.Case) {
			c.CheckThat("a listed header file: would remove", c.LogHas("would remove "+c.Path(oldConf)))
		}})
	// The header of a real run names repo/tools, in a file and in a generated
	// conf.d file.
	rc.Run(t, rc.Spec{Name: "a real run: the header paths", Values: noToolValues, Args: realRun,
		Check: func(c *rc.Case) {
			lines := strings.Split(harness.ReadFile(c.Path(".config/mise/tasks/_scripts/helpers.py")), "\n")
			c.CheckThat("a real run: line 2 of a script has the repo/tools header",
				len(lines) > 1 && strings.Contains(lines[1], "Synced from bootstrap: repo/tools/mise/tasks/helpers.py."))
			c.CheckThat("a real run: a generated conf.d file has the repo/tools header",
				rc.FileHas(c.Path(".config/mise/conf.d/mise/mise.dev.toml"), "Synced from bootstrap: repo/tools/mise/tools.toml"))
		}})
	// A consumer file with the header of the old path still counts as synced.
	rc.Run(t, rc.Spec{Name: "the old header path counts as synced", Values: noToolValues,
		Change: func(c *rc.Case) {
			consumerFile(c, "gone.txt", "# Synced from bootstrap: tools/git/gone.txt. Do not edit this file.",
				"# The next sync writes it again, and each change in this file is lost.")
			manifestFile(c, "git"+tab+"gone.txt")
		},
		Check: func(c *rc.Case) {
			c.CheckThat("the old header path: would remove", c.LogHas("would remove "+c.Path("gone.txt")))
		}})
	rc.Run(t, rc.Spec{Name: "the stale rule, a listed file without the header", Values: noToolValues,
		Change: func(c *rc.Case) {
			consumerFile(c, "own.txt", "my own file")
			manifestFile(c, "oldtool"+tab+"own.txt")
		},
		Check: func(c *rc.Case) {
			c.CheckThat("a listed file without the header: no would remove", c.LogLacks("would remove "+c.Path("own.txt")))
		}})
	rc.Run(t, rc.Spec{Name: "the stale rule, a listed file that the run writes", Values: fixtureValues,
		Change: func(c *rc.Case) {
			fixtureTxt(c)
			copySynced(c)
			manifestFile(c, "fixture"+tab+"a.txt")
		},
		Check: func(c *rc.Case) {
			c.CheckThat("a listed file that the run writes: would update", c.LogHas("would update "+c.Path("a.txt")))
			c.CheckThat("a listed file that the run writes: no would remove", c.LogLacks("would remove "+c.Path("a.txt")))
		}})
	// The manifest is a file of the consumer, so the engine does not trust
	// its rows.
	rc.Run(t, rc.Spec{Name: "the stale rule, bad rows of the manifest", Values: noToolValues,
		Change: func(c *rc.Case) {
			h := harness.Lines("# Synced from bootstrap: x. Do not edit this file.")
			abs := filepath.Join(c.Dir, "abs.txt")
			harness.WriteFile(c.T, filepath.Join(c.Dir, "outside.txt"), h)
			harness.WriteFile(c.T, abs, h)
			harness.WriteFile(c.T, c.Path("notab.txt"), h)
			manifestFile(c, "x"+tab+"../outside.txt", "x"+tab+abs, "notab.txt", tab+"notab.txt", "x"+tab,
				"x"+tab+"a/../../outside.txt")
		},
		Check: func(c *rc.Case) {
			skippedRows(c, "bad rows", 2, 3, 4, 5, 6, 7)
			c.CheckThat("bad rows: no would remove", c.LogLacks("would remove"))
		}})
}

// staleLinks: a listed path below a symlinked folder, and a listed path that
// is a symlink.
func staleLinks(c *rc.Case) {
	harness.WriteFile(c.T, outside(c, "stale.txt"), harness.Lines("# Synced from bootstrap: x. Do not edit this file."))
	symlink(c, filepath.Join(c.Dir, "outside"), c.Path("linked"))
	symlink(c, outside(c, "stale.txt"), c.Path("link.txt"))
	manifestFile(c, "x"+tab+"link.txt", "x"+tab+"linked/stale.txt")
}

func checkStaleLinks(c *rc.Case) {
	c.CheckThat("links: a symlinked folder is kept", c.LogHas("kept linked/stale.txt (link)"))
	c.CheckThat("links: a symlink is kept", c.LogHas("kept link.txt (link)"))
	c.CheckThat("links: no would remove", c.LogLacks("would remove"))
	c.CheckThat("links: no removed", c.LogLacks("removed    "+c.Path("link")))
	c.CheckThat("links: the outside file stays", isFile(outside(c, "stale.txt")))
	c.CheckThat("links: the folder link stays", linkIs(c.Path("linked"), filepath.Join(c.Dir, "outside")))
	c.CheckThat("links: the file link stays", linkIs(c.Path("link.txt"), outside(c, "stale.txt")))
}

func staleFailure(c *rc.Case) {
	fixtureBadJSON(c)
	headerFile(c, "stale.txt")
	manifestFile(c, "oldtool"+tab+"stale.txt")
}

func checkStaleFailure(c *rc.Case) {
	c.CheckThat("a failure: no would remove", c.LogLacks("would remove"))
	c.CheckThat("a failure: no removed", c.LogLacks("removed    "+c.Path("stale.txt")))
	c.CheckThat("a failure: no would write", c.LogLacks("would write "+manifestPath(c)))
	c.CheckThat("a failure: the stale file stays", isFile(c.Path("stale.txt")))
	checkExact(c, "a failure: the old manifest stays", manifestPath(c), manifestFirst+"\n"+"oldtool"+tab+"stale.txt\n")
}

func TestStaleRuleRuns(t *testing.T) {
	rc.Run(t, rc.Spec{Name: "the stale rule, listed links, a dry run", Values: noToolValues, Change: staleLinks, Check: checkStaleLinks})
	rc.Run(t, rc.Spec{Name: "the stale rule, listed links, a real run", Values: noToolValues, Args: realRun,
		Change: staleLinks, Check: checkStaleLinks})
	// The rows of a real run. A second run does not write the manifest again.
	rc.Run(t, rc.Spec{Name: "the manifest of a real run", Values: noToolValues, Args: realRun,
		Check: func(c *rc.Case) {
			file := manifestPath(c)
			c.CheckThat("the manifest: written", c.LogHas("wrote      "+file))
			first, _, _ := strings.Cut(harness.ReadFile(file), "\n")
			c.CheckThat("the manifest: the first line", first == manifestFirst)
			c.CheckThat("the manifest: the rows are sorted", manifestRowsSorted(file))
			c.CheckThat("the manifest: a generated conf.d file", hasLine(file, "mise"+tab+".config/mise/conf.d/mise/mise.dev.toml"))
			c.CheckThat("the manifest: no seed", fileLacks(file, ".config/mise/conf.d/zz-repo/"))
			c.CheckThat("the manifest: no removed merge task", fileLacks(file, ".config/mise/tasks/git/merge/develop.py"))
			got := rerun(c)
			c.CheckThat("the manifest: a second run exits 0", got == 0)
			c.CheckThat("the manifest: a second run does not write it", c.LogLacks("wrote      "+file))
		}})
	// The stale file and its empty folders go. A folder that holds a file
	// stays.
	rc.Run(t, rc.Spec{Name: "the stale rule, a real run removes the empty folders", Values: noToolValues, Args: realRun,
		Change: func(c *rc.Case) {
			headerFile(c, "a/b/stale.txt")
			headerFile(c, "c/d/stale.txt")
			consumerFile(c, "c/keep.txt", "keep")
			manifestFile(c, "oldtool"+tab+"a/b/stale.txt", "oldtool"+tab+"c/d/stale.txt")
		},
		Check: func(c *rc.Case) {
			c.CheckThat("a stale file: removed", c.LogHas("removed    "+c.Path("a/b/stale.txt")))
			c.CheckThat("a stale file: its empty folders are gone", rc.NoFile(c.Path("a")))
			c.CheckThat("a stale file: the empty folder below a kept folder is gone", rc.NoFile(c.Path("c/d")))
			c.CheckThat("a stale file: a folder with another file stays", isFile(c.Path("c/keep.txt")))
			c.CheckThat("a stale file: the new manifest has no row", fileLacks(manifestPath(c), "stale.txt"))
		}})
	// A run with a failure removes nothing, and it keeps the old manifest.
	rc.Run(t, rc.Spec{Name: "the stale rule, a dry run with a failure", Code: 2, Values: fixtureValues,
		Change: staleFailure, Message: "bad.json: the result does not parse as json", Check: checkStaleFailure})
	rc.Run(t, rc.Spec{Name: "the stale rule, a real run with a failure", Code: 2, Values: fixtureValues, Args: realRun,
		Change: staleFailure, Message: "bad.json: the result does not parse as json", Check: checkStaleFailure})
	// A seed that the run keeps, also a seed of an environment that the repo
	// does not use.
	rc.Run(t, rc.Spec{Name: "the stale rule, a listed seed", Values: noToolValues,
		Change: func(c *rc.Case) {
			headerFile(c, ".config/mise/conf.d/zz-repo/mise.dev.toml")
			headerFile(c, ".config/mise/conf.d/zz-repo/mise.ci.toml")
			manifestFile(c, "mise"+tab+".config/mise/conf.d/zz-repo/mise.ci.toml", "mise"+tab+".config/mise/conf.d/zz-repo/mise.dev.toml")
		},
		Check: func(c *rc.Case) { c.CheckThat("a listed seed: no would remove", c.LogLacks("would remove")) }})
	// A merge task of the other branch model: the engine removes it, the
	// stale rule does not log it again.
	rc.Run(t, rc.Spec{Name: "the stale rule, a listed merge task of the other model", Values: noToolValues,
		Change: func(c *rc.Case) {
			headerFile(c, ".config/mise/tasks/git/merge/develop.py")
			manifestFile(c, "git"+tab+".config/mise/tasks/git/merge/develop.py")
		},
		Check: func(c *rc.Case) {
			c.CheckThat("a listed merge task: one would remove", c.LogCount("would remove "+c.Path(".config/mise/tasks/git/merge/develop.py"), 1))
		}})
	// The bytes of the manifest, so the pre-commit hooks never rewrite it.
	rc.Run(t, rc.Spec{Name: "the bytes of the manifest", Values: noToolValues, Args: realRun,
		Check: func(c *rc.Case) {
			b := harness.ReadFile(manifestPath(c))
			c.CheckThat("the manifest bytes: a newline at the end", b == "" || strings.HasSuffix(b, "\n"))
			c.CheckThat("the manifest bytes: one newline at the end", strings.HasSuffix(b, "\n") && !strings.HasSuffix(b, "\n\n"))
			c.CheckThat("the manifest bytes: no CR", !strings.Contains(b, "\r"))
			c.CheckThat("the manifest bytes: no trailing blank", !strings.Contains(b, " \n") && !strings.HasSuffix(b, " "))
		}})
	// A dry run names the manifest that differs, and writes nothing.
	rc.Run(t, rc.Spec{Name: "a dry run, a manifest that differs", Values: noToolValues,
		Change: func(c *rc.Case) { manifestFile(c, "oldtool"+tab+"nothing.txt") },
		Check: func(c *rc.Case) {
			c.CheckThat("a manifest that differs: would write", c.LogHas("would write "+manifestPath(c)))
			checkExact(c, "a manifest that differs: a dry run writes nothing", manifestPath(c),
				manifestFirst+"\n"+"oldtool"+tab+"nothing.txt\n")
		}})
}

// staleUncleanRows: rows with an empty, `.` or `..` segment are not a clean
// path, also when they name a real file below the root.
func staleUncleanRows(c *rc.Case) {
	headerFile(c, "a.txt")
	headerFile(c, "d/a.txt")
	manifestFile(c, "x"+tab+"./a.txt", "x"+tab+".//a.txt", "x"+tab+"d//a.txt", "x"+tab+"d/./a.txt", "x"+tab+"d/")
}

func checkStaleUncleanRows(c *rc.Case) {
	skippedRows(c, "unclean rows", 2, 3, 4, 5, 6)
	c.CheckThat("unclean rows: no remove", c.LogLacks("remove"))
	c.CheckThat("unclean rows: a.txt stays", isFile(c.Path("a.txt")))
	c.CheckThat("unclean rows: d/a.txt stays", isFile(c.Path("d/a.txt")))
}

// staleCaseVariant: a row with a case variant of a file that the run
// handles. A file system that ignores case finds the same file, and on
// another one the row names no file.
func staleCaseVariant(c *rc.Case) {
	fixtureTxt(c)
	copySynced(c)
	manifestFile(c, "fixture"+tab+"A.TXT")
}

func checkStaleCaseVariant(c *rc.Case) {
	c.CheckThat("a case variant: no remove", c.LogLacks("remove"))
	c.CheckThat("a case variant: the file stays with its header", rc.FileHas(c.Path("a.txt"), "Synced from bootstrap"))
}

func TestStaleRows(t *testing.T) {
	rc.Run(t, rc.Spec{Name: "the stale rule, unclean rows, a dry run", Values: noToolValues,
		Change: staleUncleanRows, Check: checkStaleUncleanRows})
	rc.Run(t, rc.Spec{Name: "the stale rule, unclean rows, a real run", Values: noToolValues, Args: realRun,
		Change: staleUncleanRows, Check: checkStaleUncleanRows})
	rc.Run(t, rc.Spec{Name: "the stale rule, a case variant of a handled file, a dry run", Values: fixtureValues,
		Change: staleCaseVariant, Check: checkStaleCaseVariant})
	rc.Run(t, rc.Spec{Name: "the stale rule, a case variant of a handled file, a real run", Values: fixtureValues, Args: realRun,
		Change: staleCaseVariant, Check: checkStaleCaseVariant})
	// A row with a `.git` segment, in any case and at any depth.
	rc.Run(t, rc.Spec{Name: "the stale rule, rows with a .git segment", Values: noToolValues, Args: realRun,
		Change: func(c *rc.Case) {
			headerFile(c, ".git/hooks/h")
			headerFile(c, ".GIT/hooks/h")
			headerFile(c, "sub2/.git/h")
			manifestFile(c, "x"+tab+".git/hooks/h", "x"+tab+".GIT/hooks/h", "x"+tab+"sub2/.git/h")
		},
		Check: func(c *rc.Case) {
			skippedRows(c, ".git rows", 2, 3, 4)
			c.CheckThat(".git rows: no remove", c.LogLacks("remove"))
			c.CheckThat(".git rows: .git/hooks/h stays", isFile(c.Path(".git/hooks/h")))
			c.CheckThat(".git rows: .GIT/hooks/h stays", isFile(c.Path(".GIT/hooks/h")))
			c.CheckThat(".git rows: sub2/.git/h stays", isFile(c.Path("sub2/.git/h")))
		}})
	// A listed file of a git submodule: that repository has its own
	// manifest. The row with a case variant finds the submodule only on a
	// file system that ignores case.
	rc.Run(t, rc.Spec{Name: "the stale rule, a listed file of a submodule", Values: noToolValues, Args: realRun,
		Change: func(c *rc.Case) {
			consumerWithSubmodule(c)
			headerFile(c, "sub/stale.txt")
			manifestFile(c, "x"+tab+"sub/stale.txt", "x"+tab+"SUB/stale.txt")
		},
		Check: func(c *rc.Case) {
			c.CheckThat("a submodule: the row is kept", c.LogHas("kept sub/stale.txt (another repository)"))
			if exists(c.Path("SUB")) {
				c.CheckThat("a submodule: the case variant is kept", c.LogHas("kept SUB/stale.txt (another repository)"))
			}
			c.CheckThat("a submodule: no remove", c.LogLacks("remove"))
			c.CheckThat("a submodule: the file stays", isFile(c.Path("sub/stale.txt")))
		}})
	// A folder member is part of the root tree, but a nested clone is not,
	// also when the values file names it as a folder member.
	staleFolderMember := func(c *rc.Case) {
		headerFile(c, "mem/stale.txt")
		manifestFile(c, "x"+tab+"mem/stale.txt")
	}
	rc.Run(t, rc.Spec{Name: "the stale rule, a listed file of a folder member", Values: memberMemValues, Args: realRun,
		Change: staleFolderMember,
		Check: func(c *rc.Case) {
			c.CheckThat("a folder member: removed", c.LogHas("removed    "+c.Path("mem/stale.txt")))
			c.CheckThat("a folder member: the file is gone", rc.NoFile(c.Path("mem/stale.txt")))
		}})
	rc.Run(t, rc.Spec{Name: "the stale rule, a listed file of a nested clone that is a folder member", Values: memberMemValues,
		Args: realRun,
		Change: func(c *rc.Case) {
			staleFolderMember(c)
			harness.Git(c.T, c.Path("mem"), "init", "--quiet")
			harness.Git(c.T, c.Path("mem"), "commit", "--quiet", "--no-verify", "--allow-empty", "-m", "nested")
			// The commit of the case must not add the nested clone as a
			// gitlink: a gitlink that is not in .gitmodules stops the run.
			harness.WriteFile(c.T, c.Path(".git/info/exclude"), "mem\n")
		},
		Check: func(c *rc.Case) {
			c.CheckThat("a nested clone: the row is kept", c.LogHas("kept mem/stale.txt (another repository)"))
			c.CheckThat("a nested clone: no remove", c.LogLacks("remove"))
			c.CheckThat("a nested clone: the file stays", isFile(c.Path("mem/stale.txt")))
		}})
}

// manifestRefusedStale: a stale file, listed in a manifest outside the
// repository.
func manifestRefusedStale(c *rc.Case) {
	headerFile(c, "stale.txt")
	harness.WriteFile(c.T, outside(c, "manifest.tsv"), harness.Lines(manifestFirst, "oldtool"+tab+"stale.txt"))
}

func manifestIsLink(c *rc.Case) {
	manifestRefusedStale(c)
	mkdir(c, c.Values)
	symlink(c, outside(c, "manifest.tsv"), manifestPath(c))
}

// checkManifestRefused: the sync failed at the manifest, with its message
// after the path of the manifest.
func checkManifestRefused(c *rc.Case, msg string) {
	c.CheckThat("a refused manifest: the message", c.LogHas(manifestPath(c)+": "+msg))
	c.CheckThat("a refused manifest: FAILED", c.LogHas("FAILED: .config/bootstrap/repo-generated.tsv"))
	c.CheckThat("a refused manifest: no remove", c.LogLacks("remove"))
	c.CheckThat("a refused manifest: no bootstrap_commit in the log", c.LogLacks("bootstrap_commit"))
	c.CheckThat("a refused manifest: no bootstrap_commit", fileLacks(c.RepoValues, "bootstrap_commit"))
	c.CheckThat("a refused manifest: the stale file stays", isFile(c.Path("stale.txt")))
}

func checkManifestLink(c *rc.Case) { checkManifestRefused(c, manifestLinkMessage) }
func checkManifestKind(c *rc.Case) { checkManifestRefused(c, manifestKindMessage) }

// A manifest that is a link, that is below a link or that is not a regular
// file is not read. The stale file is listed in the file behind the link.
func TestManifestRefused(t *testing.T) {
	rc.Run(t, rc.Spec{Name: "the manifest is a symlink, a dry run", Code: 2, Values: noToolValues,
		Change: manifestIsLink, Message: manifestLinkMessage, Check: checkManifestLink})
	rc.Run(t, rc.Spec{Name: "the manifest is a symlink, a real run", Code: 2, Values: noToolValues, Args: realRun,
		Change: manifestIsLink, Message: manifestLinkMessage, Check: checkManifestLink})
	rc.Run(t, rc.Spec{Name: "the manifest is a dangling symlink", Code: 2, Values: noToolValues, Args: realRun,
		Change: func(c *rc.Case) {
			manifestRefusedStale(c)
			symlink(c, outside(c, "none.tsv"), manifestPath(c))
		}, Message: manifestLinkMessage, Check: checkManifestLink})
	// A shared file below the symlinked .config fails too, so the run fails
	// before its manifest step.
	rc.Run(t, rc.Spec{Name: "the manifest is below a symlinked .config", Code: 2, Values: noToolValues, Args: realRun,
		Change: func(c *rc.Case) {
			manifestRefusedStale(c)
			rename(c, outside(c, "manifest.tsv"), manifestPath(c))
			rename(c, c.Path(".config"), outside(c, "config"))
			symlink(c, outside(c, "config"), c.Path(".config"))
		}, Message: manifestLinkMessage,
		Check: func(c *rc.Case) {
			c.CheckThat("a manifest below a link: the message", c.LogHas(manifestPath(c)+": "+manifestLinkMessage))
			c.CheckThat("a manifest below a link: the shared file fails",
				c.LogHas("FAILED: repo/tools/pre-commit/files/.config/pre-commit-config.yaml.merge.toml"))
			c.CheckThat("a manifest below a link: no remove", c.LogLacks("remove"))
			c.CheckThat("a manifest below a link: no bootstrap_commit", fileLacks(c.RepoValues, "bootstrap_commit"))
			c.CheckThat("a manifest below a link: the stale file stays", isFile(c.Path("stale.txt")))
		}})
	manifestIsFolder := func(c *rc.Case) {
		manifestRefusedStale(c)
		mkdir(c, manifestPath(c))
	}
	rc.Run(t, rc.Spec{Name: "the manifest is a folder, a dry run", Code: 2, Values: noToolValues,
		Change: manifestIsFolder, Message: manifestKindMessage, Check: checkManifestKind})
	rc.Run(t, rc.Spec{Name: "the manifest is a folder, a real run", Code: 2, Values: noToolValues, Args: realRun,
		Change: manifestIsFolder, Message: manifestKindMessage, Check: checkManifestKind})
	rc.Run(t, rc.Spec{Name: "the manifest is a FIFO", Code: 2, Values: noToolValues, Args: realRun,
		Change: func(c *rc.Case) {
			manifestRefusedStale(c)
			mkfifo(c, manifestPath(c))
		}, Message: manifestKindMessage, Check: checkManifestKind})
}
