const (
	claudeNodeValues = `environments = [ "dev" ]
[tools.claude]
[tools.node]`
	claudePnpmValues = `environments = [ "dev" ]
[tools.claude]
[tools.node]
[tools.pnpm]`
	claudeNoSkillsValues = `environments = [ "dev" ]
[tools.claude]
skills = false
[tools.node]
[tools.pnpm]`
	claudeJavaValues = `environments = [ "dev" ]
[tools.claude]
[tools.java]`
	claudeJavaKotlinValues = `environments = [ "dev" ]
[tools.claude]
[tools.java]
[tools.kotlin]`
	noClaudeValues = `environments = [ "dev" ]
[tools.node]
[tools.pnpm]`
	sectionStartLine = "<!-- bootstrap:start - the next sync writes this part again, and a change in it is lost -->"
	sectionEndLine   = "<!-- bootstrap:end - add own text below this line -->"
	ownClaudeMd      = "# My project\n\nMy own rules.\n"
	// pnpmDepLine is the start of the dependency line of the pnpm tool.
	pnpmDepLine = "- pnpm 11 ignores onlyBuiltDependencies"
	tsSkill     = ".claude/skills/typescript/SKILL.md"
	pnpmSkill   = ".claude/skills/pnpm/SKILL.md"
	tsLocal     = ".claude/skills/typescript/references/local.md"
	gradleSkill = ".claude/skills/gradle/SKILL.md"
)

// ownClaude: a CLAUDE.md of the consumer with own text.
func ownClaude(c *rc.Case) { harness.WriteFile(c.T, c.Path("CLAUDE.md"), ownClaudeMd) }

// lineAt gives the line <n> (from 1) of the file, or "".
func lineAt(path string, n int) string {
	lines := strings.Split(harness.ReadFile(path), "\n")
	if n > len(lines) {
		return ""
	}
	return lines[n-1]
}

// sectionOnTop: CLAUDE.md starts with the shared-file header and the
// section, and the own text of the user comes after its end line, unchanged.
func sectionOnTop(c *rc.Case) bool {
	text := harness.ReadFile(c.Path("CLAUDE.md"))
	before, rest, ok := strings.Cut(text, sectionStartLine+"\n")
	if !ok || !strings.HasPrefix(before, "<!-- Shared with bootstrap: repo/tools/claude/files/CLAUDE.md.merge.toml. -->\n") {
		return false
	}
	for _, l := range strings.Split(strings.TrimSuffix(before, "\n"), "\n") {
		if !strings.HasPrefix(l, "<!-- ") || !strings.HasSuffix(l, " -->") {
			return false
		}
	}
	_, after, ok := strings.Cut(rest, sectionEndLine+"\n")
	return ok && after == "\n"+ownClaudeMd
}

// skillHeader: the skill file has --- on line 1 and the bootstrap header on
// lines 2 and 3.
func skillHeader(c *rc.Case, rel string) bool {
	p := c.Path(rel)
	return lineAt(p, 1) == "---" &&
		strings.HasPrefix(lineAt(p, 2), "# Synced from bootstrap: ") &&
		strings.HasSuffix(lineAt(p, 2), ". Do not edit this file.") &&
		lineAt(p, 3) == "# The next sync writes it again, and each change in this file is lost."
}

// checkSection: the three parts of the section, then the own text.
func checkSection(c *rc.Case, name string) {
	p := c.Path("CLAUDE.md")
	c.CheckThat(name+": the section is at the top, above the own text", sectionOnTop(c))
	c.CheckThat(name+": the Tasks part", hasLine(p, "**Tasks**"))
	c.CheckThat(name+": the Dependencies part", hasLine(p, "**Dependencies**"))
	c.CheckThat(name+": the Gates part", hasLine(p, "**Gates**"))
}

// The bootstrap section of CLAUDE.md and the skills of the selected tools,
// which the claude tool ships (D2, D3 of plan 2026-11-27-tool-skills).
func TestClaudeFiles(t *testing.T) {
	rc.Run(t, rc.Spec{Name: "claude: node, the section and the typescript skill", Values: claudeNodeValues, Args: realRun,
		Change: ownClaude,
		Check: func(c *rc.Case) {
			checkSection(c, "claude node")
			c.CheckThat("claude node: no pnpm dependency line", notGrep(`^`+pnpmDepLine, c.Path("CLAUDE.md")))
			c.CheckThat("claude node: the typescript skill has the frontmatter and the header", skillHeader(c, tsSkill))
			c.CheckThat("claude node: the typescript references", notEmpty(c.Path(".claude/skills/typescript/references/conventions.md")) &&
				notEmpty(c.Path(tsLocal)))
			c.CheckThat("claude node: no pnpm skill", !exists(c.Path(".claude/skills/pnpm")))
		}})
	rc.Run(t, rc.Spec{Name: "claude: pnpm, its dependency line and its skill", Values: claudePnpmValues, Args: realRun,
		Change: ownClaude,
		Check: func(c *rc.Case) {
			checkSection(c, "claude pnpm")
			c.CheckThat("claude pnpm: the pnpm dependency line", !notGrep(`^`+pnpmDepLine, c.Path("CLAUDE.md")))
			c.CheckThat("claude pnpm: the pnpm skill has the frontmatter and the header", skillHeader(c, pnpmSkill))
			c.CheckThat("claude pnpm: the typescript skill", skillHeader(c, tsSkill))
		}})
	rc.Run(t, rc.Spec{Name: "claude: skills = false, no skill and the section", Values: claudeNoSkillsValues, Args: realRun,
		Change: ownClaude,
		Check: func(c *rc.Case) {
			checkSection(c, "claude no skills")
			c.CheckThat("claude no skills: no skill file", !exists(c.Path(".claude/skills")))
		}})
	rc.Run(t, rc.Spec{Name: "claude: not selected, no section and no skill", Values: noClaudeValues, Args: realRun,
		Change: ownClaude,
		Check: func(c *rc.Case) {
			checkExact(c, "no claude: CLAUDE.md stays", c.Path("CLAUDE.md"), ownClaudeMd)
			c.CheckThat("no claude: no skill", !exists(c.Path(".claude")))
		}})
	rc.Run(t, rc.Spec{Name: "claude: a second sync keeps the own text and local.md", Values: claudePnpmValues, Args: realRun,
		Change: ownClaude,
		Check: func(c *rc.Case) {
			harness.AppendFile(c.T, c.Path("CLAUDE.md"), "A rule of the user.\n")
			harness.WriteFile(c.T, c.Path(tsLocal), "# Local rules\n\nMy own typescript rule.\n")
			want := harness.ReadFile(c.Path("CLAUDE.md"))
			got := rerun(c)
			c.CheckThat("claude second sync: exits 0", got == 0)
			checkExact(c, "claude second sync: CLAUDE.md keeps the line after bootstrap:end", c.Path("CLAUDE.md"), want)
			checkExact(c, "claude second sync: the edited local.md stays", c.Path(tsLocal),
				"# Local rules\n\nMy own typescript rule.\n")
		}})
}

// gradleKotlinLines: the kotlin-only lines of the gradle skill of the java tool.
var gradleKotlinLines = []string{
	"`setup:deps:30-kotlin` runs Gradle with `--no-configuration-cache`",
	"- Without the ben-manes plugin, `mise run setup --upgrade` does not give the",
	"- The locking rules are in the bootstrap section of `CLAUDE.md`.",
}

// The gradle skill of the java tool has its kotlin-only lines only when
// kotlin is selected.
func TestClaudeGradleSkill(t *testing.T) {
	rc.Run(t, rc.Spec{Name: "claude: java without kotlin, the gradle skill has no kotlin line", Values: claudeJavaValues, Args: realRun,
		Check: func(c *rc.Case) {
			p := c.Path(gradleSkill)
			c.CheckThat("claude java: the gradle skill has the frontmatter and the header", skillHeader(c, gradleSkill))
			c.CheckThat("claude java: the gradle skill has the cache line",
				hasLine(p, "  (`org.gradle.caching=true` and `org.gradle.configuration-cache=true`)."))
			for _, l := range gradleKotlinLines {
				c.CheckThat("claude java: no kotlin line: "+l, fileLacks(p, l))
			}
		}})
	rc.Run(t, rc.Spec{Name: "claude: java and kotlin, the gradle skill has the kotlin lines", Values: claudeJavaKotlinValues, Args: realRun,
		Check: func(c *rc.Case) {
			p := c.Path(gradleSkill)
			c.CheckThat("claude java kotlin: the gradle skill has the frontmatter and the header", skillHeader(c, gradleSkill))
			for _, l := range gradleKotlinLines {
				c.CheckThat("claude java kotlin: the kotlin line: "+l, rc.FileHas(p, l))
			}
		}})
}
