// rerun runs `bootstrap sync` again in the case (case_rerun). Its output
// replaces the log of the case.
func rerun(c *rc.Case) int {
	c.CommitConsumer()
	f, err := os.Create(c.Log)
	if err != nil {
		c.T.Fatal(err)
	}
	defer func() { _ = f.Close() }()
	env := harness.SetEnv(c.Env, "FORCE_COLOR", "BOOTSTRAP_URL", "BOOTSTRAP_CLONE="+c.Clone)
	cmd := &harness.Cmd{Env: env, Out: f, Args: []string{harness.Bin, "sync"}}
	code, _ := cmd.Run()
	return code
}

// checkLogLacks records the check "<name>: no <text>" (check_log_lacks).
func checkLogLacks(c *rc.Case, name, text string) {
	c.T.Helper()
	if c.LogHas(text) {
		c.Fail(name + ": the output has: " + text)
	} else {
		c.Pass(name + ": no " + text)
	}
}

// checkExact records the check <name>: the file <path> holds <content>,
// byte for byte (check_exact).
func checkExact(c *rc.Case, name, path, content string) {
	c.T.Helper()
	got := harness.ReadFile(path)
	if got == content {
		c.Pass(name)
	} else {
		harness.Fail(c.T, name+": "+path+" changed", got)
	}
}

// fileLacks is lacks_in_file: the file does not have the fixed string <s>.
func fileLacks(path, s string) bool { return !rc.FileHas(path, s) }

// notGrep is not_grep: no line of the file matches the regular expression.
func notGrep(re, path string) bool {
	return !regexp.MustCompile("(?m)" + re).MatchString(harness.ReadFile(path))
}

// hasLine is grep -qxF: the file has the line <line>.
func hasLine(path, line string) bool { return countLine(path, line) > 0 }

// countLine is grep -cxF.
func countLine(path, line string) int {
	n := 0
	for _, l := range strings.Split(harness.ReadFile(path), "\n") {
		if l == line {
			n++
		}
	}
	return n
}

// isFile is test -f.
func isFile(path string) bool {
	fi, err := os.Stat(path)
	return err == nil && fi.Mode().IsRegular()
}

// notEmpty is test -s.
func notEmpty(path string) bool {
	fi, err := os.Stat(path)
	return err == nil && fi.Size() > 0
}

// exists is test -e.
func exists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

// linkIs: <link> is a symlink to <target>.
func linkIs(link, target string) bool {
	fi, err := os.Lstat(link)
	if err != nil || fi.Mode()&os.ModeSymlink == 0 {
		return false
	}
	got, err := os.Readlink(link)
	return err == nil && got == target
}

// jsonIs: the file <path> holds the JSON value <want>. On a mismatch, the
// log gets the file, so the failure shows it.
func jsonIs(c *rc.Case, path, want string) bool {
	var g, w any
	raw, err := os.ReadFile(path)
	gotText := ""
	if err == nil {
		err = json.Unmarshal(raw, &g)
	}
	if err != nil {
		gotText = "(no JSON) " + err.Error()
	} else {
		b, _ := json.Marshal(g)
		gotText = string(b)
	}
	if err := json.Unmarshal([]byte(want), &w); err != nil {
		c.T.Fatal(err)
	}
	wb, _ := json.Marshal(w)
	if gotText == string(wb) {
		return true
	}
	harness.AppendFile(c.T, c.Log, harness.Lines(path+" holds: "+gotText, "expected: "+string(wb)))
	return false
}

// toolsHas: the `tools:` line of the output has the word <tool>.
func toolsHas(c *rc.Case, tool string) bool {
	re := regexp.MustCompile(`(^|[^A-Za-z0-9_])` + regexp.QuoteMeta(tool) + `([^A-Za-z0-9_]|$)`)
	for _, l := range strings.Split(c.LogText(), "\n") {
		if strings.Contains(l, "bootstrap: tools:") && re.MatchString(l) {
			return true
		}
	}
	return false
}

// regularFiles gives the regular files below <dir>. It follows no symlink.
func regularFiles(dir string) []string {
	var out []string
	_ = filepath.WalkDir(dir, func(p string, e fs.DirEntry, err error) error {
		if err == nil && e.Type().IsRegular() {
			out = append(out, p)
		}
		return nil
	})
	return out
}

// repoLacks: no regular file of the consumer has the fixed string <s>.
func repoLacks(c *rc.Case, s string) bool {
	for _, p := range regularFiles(c.Consumer) {
		if rc.FileHas(p, s) {
			return false
		}
	}
	return true
}

// outsideOnlyFile: the folder outside holds only the file m.json.
func outsideOnlyFile(c *rc.Case) bool {
	var out []string
	root := filepath.Join(c.Dir, "outside")
	_ = filepath.WalkDir(root, func(p string, e fs.DirEntry, err error) error {
		if err == nil && !e.IsDir() {
			out = append(out, p)
		}
		return nil
	})
	return len(out) == 1 && out[0] == filepath.Join(root, "m.json")
}

// manifestRowsSorted: the rows after the first line are in byte order.
func manifestRowsSorted(path string) bool {
	lines := strings.Split(strings.TrimSuffix(harness.ReadFile(path), "\n"), "\n")
	if len(lines) < 2 {
		return true
	}
	return sort.StringsAreSorted(lines[1:])
}

