// Package misegen is the mise config generator of the sync engine. It
// replaces `sync-engine/mise` of the bash engine, for both sides (repo and
// macos), with the same messages, exit codes and output bytes.
//
//   - EnvName and NewEnvs: the environments of each tool and of each mise tool
//     (`_se_mise_env_name`, `_se_mise_envs`).
//   - Generator.Overrides: the checks of `[overrides.mise*]` of the values
//     file (`_se_mise_overrides`).
//   - Generator.Render: the files conf.d/<tool>/mise.<env>.toml (repo) or
//     conf.d/<tool>/mise.toml (macos) of one tool (`_se_mise_render`).
//   - Generator.OwnConfig: conf.d/zz-macos/mise.toml from the [mise] tables
//     of macos.toml (`_se_mise_own_config`).
//
// Each render goes through internal/tmpl with the gomplate templates of the
// bash engine, byte for byte. Each message is a *fail.Error in the returned
// error (see source.LogAll). A front-end prints them with its prefix.
//
// Contract: docs/design/mise.md.
package misegen

import (
	"strings"

	"github.com/virajp/bootstrap/sync-engine/internal/fail"
	"github.com/virajp/bootstrap/sync-engine/internal/selection"
	"github.com/virajp/bootstrap/sync-engine/internal/source"
)

// MacosValues is the name of the values file of the Mac in a message and in
// the override note (_SE_MISE_MACOS_VALUES).
const MacosValues = "macos.toml"

// EnvNames are the environment names that a tools.toml can use in
// `default_envs` and `envs`, in their order (_SE_MISE_ENV_NAMES).
var EnvNames = []string{"dev", "ci"}

// envNamesText is _SE_MISE_ENV_NAMES with ", " between the names.
var envNamesText = strings.Join(EnvNames, ", ")

// The header lines of a generated file.
// Copy of internal/header; the coordinator replaces it at the merge.
const (
	headerLine1 = "Synced from bootstrap: %s. Do not edit this file."
	headerLine2 = "The next sync replaces it, and a manual change is lost."
)

func usage(format string, args ...any) *fail.Error { return fail.New(fail.Usage, format, args...) }

// checkSide is `_se_mise_side`: nil for repo and macos, else a usage error.
func checkSide(side source.Side) error {
	if side == source.Repo || side == source.Macos {
		return nil
	}
	return usage("sync-engine/mise: the side must be repo or macos, not '%s'", side)
}

// EnvName is `_se_mise_env_name`: true when <name> is one of EnvNames.
func EnvName(name string) bool {
	if name == "" || strings.ContainsAny(name, " \t\n\v\f\r") {
		return false
	}
	for _, n := range EnvNames {
		if n == name {
			return true
		}
	}
	return false
}

// words is a list in the form of the bash variables: " a b " (" " when empty).
type words []string

func (w words) String() string {
	s := " "
	for _, x := range w {
		s += x + " "
	}
	return s
}

func (w words) has(x string) bool {
	for _, y := range w {
		if y == x {
			return true
		}
	}
	return false
}

// Envs is the result of `_se_mise_envs`.
type Envs struct {
	// Selected holds the selected environments (_SE_MISE_SELECTED). It is
	// empty on the macos side.
	Selected []string
	tools    words // "<tool>:<env>" (_SE_MISE_TOOL_ENVS)
	mise     words // "<mise-tool>:<env>" (_SE_MISE_ENVS)
}

// In tells if <tool> is in the environment <env>.
func (e *Envs) In(tool, env string) bool { return e != nil && e.tools.has(tool+":"+env) }

// ToolWords gives _SE_MISE_TOOL_ENVS: the " <tool>:<env> " words.
func (e *Envs) ToolWords() string { return e.tools.String() }

// MiseWords gives _SE_MISE_ENVS: the " <mise-tool>:<env> " words.
func (e *Envs) MiseWords() string { return e.mise.String() }

// NewEnvs is `_se_mise_envs`. <selected> holds the environments of the
// values file, in the order of EnvNames. <r> is the resolved selection: its
// Sel entries, its Deps rows, and the default_envs and the [mise.tools] entries
// of each tool of r.Tools. <shown> is the tools folder in a message
// (repo/tools). <hasFile> finds a name of `requires_found`. A tool that runs in
// an environment needs its dependencies there too. The error (code 2) is an
// unknown name in `envs`, or a tool in an environment that one of its mise
// tools does not allow. The macos side has no environments: it gives an empty
// result.
func NewEnvs(side source.Side, selected []string, r *selection.Resolved, shown string, hasFile func(string) bool) (*Envs, error) {
	if err := checkSide(side); err != nil {
		return nil, err
	}
	e := &Envs{}
	if side != source.Repo {
		return e, nil
	}
	// The bash function reads text: build each input as the same words.
	sel := words(nil)
	for _, w := range selected {
		sel = append(sel, strings.Fields(w)...)
	}
	e.Selected = append([]string(nil), sel...)
	var defaults words
	type entry struct{ tool, line string }
	var entries []entry
	found := map[string][]string{}
	for _, tool := range r.Tools {
		m := r.Index.Manifests[tool]
		if m == nil {
			continue
		}
		for _, d := range m.DefaultEnvs {
			defaults = append(defaults, tool+":"+d)
		}
		for _, mt := range m.Mise {
			envs := "-"
			if mt.Envs != nil {
				envs = strings.Join(mt.Envs, ",")
			}
			line := mt.Name + " " + envs
			for _, d := range mt.Depends {
				line += " " + d
			}
			entries = append(entries, entry{tool, line})
			found[mt.Name] = append(found[mt.Name], mt.RequiresFound...)
		}
	}
	// reasons: why the tool is in the environment, for the message of a mise
	// tool that does not allow it.
	reasons := map[string]string{}
	for _, s := range r.Sel {
		f := strings.Fields(s.Line())
		if len(f) == 0 {
			continue
		}
		tool, envs, src := f[0], "", ""
		if len(f) > 1 {
			envs = f[1]
		}
		if len(f) > 2 {
			src = strings.Join(f[2:], " ")
		}
		if envs == "-" {
			envs = ""
			for _, d := range defaults {
				if strings.HasPrefix(d, tool+":") {
					envs += d[len(tool)+1:] + ","
				}
			}
			src = "default"
		}
		for _, env := range strings.Fields(strings.ReplaceAll(envs, ",", " ")) {
			if !sel.has(env) || e.tools.has(tool+":"+env) {
				continue
			}
			e.tools = append(e.tools, tool+":"+env)
			reasons[tool+":"+env] = src
		}
	}
	for changed := true; changed; {
		changed = false
		for _, row := range r.Deps {
			for _, env := range sel {
				if !e.tools.has(row.Tool + ":" + env) {
					continue
				}
				for _, dep := range row.Deps {
					for _, d := range strings.Fields(dep) {
						if !e.tools.has(d + ":" + env) {
							e.tools = append(e.tools, d+":"+env)
							reasons[d+":"+env] = row.Tool
							changed = true
						}
					}
				}
			}
		}
	}
	for _, en := range entries {
		f := strings.Fields(en.line)
		if len(f) == 0 {
			continue
		}
		name, allowed := f[0], ""
		if len(f) > 1 {
			allowed = f[1]
		}
		if allowed == "-" {
			allowed = "dev"
		}
		present := true
		for _, item := range found[name] {
			if !hasFile(item) {
				present = false
			}
		}
		for _, n := range strings.Fields(strings.ReplaceAll(allowed, ",", " ")) {
			if !EnvName(n) {
				return nil, usage("envs of mise tool '%s' in %s/%s/tools.toml: '%s' is not one of %s", name, shown, en.tool, n, envNamesText)
			}
		}
		only := strings.ReplaceAll(allowed, ",", ", ")
		for _, env := range sel {
			if !e.tools.has(en.tool + ":" + env) {
				continue
			}
			if !strings.Contains(","+allowed+",", ","+env+",") {
				from := reasons[en.tool+":"+env]
				switch {
				case from == "default":
					return nil, usage("%s/%s/tools.toml: default_envs has '%s', but its mise tool '%s' allows only %s", shown, en.tool, env, name, only)
				case strings.HasPrefix(from, "tools.") || strings.HasPrefix(from, "packs."):
					return nil, usage("env '%s' of [%s] in the values file: mise tool '%s' of %s/%s allows only %s", env, from, name, shown, en.tool, only)
				default:
					return nil, usage("%s/%s needs %s/%s in '%s', but its mise tool '%s' allows only %s", shown, from, shown, en.tool, env, name, only)
				}
			}
			if !present {
				continue
			}
			if !e.mise.has(name + ":" + env) {
				e.mise = append(e.mise, name+":"+env)
			}
		}
	}
	return e, nil
}
