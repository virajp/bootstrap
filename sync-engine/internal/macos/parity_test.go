package macos

// The parity test runs the Go front-end (a built binary) and the bash
// function `setup_sync` with the same inputs, and compares the exit code, the
// output and the files of each step. The inputs are the fixtures of
// test:setup-sync (macos/fixtures/): one case for each fixture config, and
// some cases with a changed home folder or clone.
//
// The golden files in testdata/golden/ hold the bash results, with a
// fingerprint of the inputs and of the bash files. UPDATE_GOLDEN=1 writes them
// again from bash. SYNC_ENGINE_LIVE=1 runs bash live. A golden file with an
// old fingerprint runs bash live, or skips the case when the bash tools
// (gomplate, jq and yq through mise) are not installed.

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"sort"
	"strings"
	"sync"
	"testing"
)

// The root of the repository, from the folder of this package.
const repoRoot = "../../.."

var (
	bashOnce sync.Once
	bashOK   bool
	binOnce  sync.Once
	binPath  string
	binErr   error
)

// bashAvailable tells if the tools of the bash engine are installed.
func bashAvailable() bool {
	bashOnce.Do(func() {
		bashOK = true
		for _, tool := range []string{"gomplate", "jq", "yq"} {
			out, err := exec.Command("sh", "-c", "cd / && MISE_OFFLINE=1 mise ls --installed "+tool+" 2>/dev/null </dev/null").Output()
			if err != nil || strings.TrimSpace(string(out)) == "" {
				bashOK = false
			}
		}
	})
	return bashOK
}

// binary builds the command once for the test run.
func binary(t *testing.T) string {
	binOnce.Do(func() {
		dir, err := os.MkdirTemp("", "macos-test-bin.")
		if err != nil {
			binErr = err
			return
		}
		binPath = filepath.Join(dir, "sync-engine")
		goCmd := filepath.Join(runtime.GOROOT(), "bin", "go")
		if _, err := os.Stat(goCmd); err != nil {
			goCmd = "go"
		}
		out, err := exec.Command(goCmd, "build", "-o", binPath, "../../cmd/sync-engine").CombinedOutput()
		if err != nil {
			binErr = fmt.Errorf("go build: %v\n%s", err, out)
		}
	})
	if binErr != nil {
		t.Fatal(binErr)
	}
	return binPath
}

func TestMain(m *testing.M) {
	code := m.Run()
	if binPath != "" {
		os.RemoveAll(filepath.Dir(binPath))
	}
	os.Exit(code)
}

// pcase is one case: steps that run one after the other in one home folder.
type pcase struct {
	name    string
	config  string // A fixture config folder, "-" for an empty one, "" for none.
	bad     bool   // The clone has the fixture tool `bad`.
	quiet   bool   // Without SYNC_ENGINE_VERBOSE=1.
	prepare func(d string)
	steps   [][]string
}

var (
	dryReal = [][]string{{"--dry-run"}, {"--no-bootstrap"}, {"--no-bootstrap"}, {"--dry-run"}}
)

func write(path, content string) {
	_ = os.MkdirAll(filepath.Dir(path), 0o755)
	_ = os.WriteFile(path, []byte(content), 0o644)
}

func cases(t *testing.T) []pcase {
	entries, err := os.ReadDir(filepath.Join(repoRoot, "macos", "fixtures", "config"))
	if err != nil {
		t.Fatal(err)
	}
	var out []pcase
	for _, e := range entries {
		out = append(out, pcase{name: "config-" + e.Name(), config: e.Name(), steps: dryReal})
	}
	header := "# Synced from bootstrap: test. Do not edit this file.\n"
	out = append(out,
		pcase{name: "help", config: "ok", steps: [][]string{{"--dry-run", "-h"}, {"--help"}}},
		pcase{name: "unknown-flag", config: "ok", steps: [][]string{{"--bogus"}, {"--dry-run", "x"}}},
		pcase{name: "no-config-folder", steps: [][]string{{"--dry-run"}}},
		pcase{name: "empty-config", config: "-", steps: dryReal},
		pcase{name: "bad-tool", config: "ok", bad: true, steps: [][]string{{"--dry-run"}}},
		pcase{name: "default-output", config: "ok", quiet: true, steps: dryReal},
		pcase{name: "stale-and-links", config: "ok", steps: dryReal, prepare: func(d string) {
			write(filepath.Join(d, "home", ".config", "old", "stale.txt"), header+"stale\n")
			write(filepath.Join(d, "home", ".config", "old", "own.txt"), "own\n")
			write(filepath.Join(d, "xdg", "cache", "sync-engine", "macos-generated.tsv"),
				"core\t.config/old/stale.txt\ncore\t.config/old/own.txt\nbad row\n")
			write(filepath.Join(d, "user", "values.txt"), "user\n")
			_ = os.MkdirAll(filepath.Join(d, "home", ".config", "core"), 0o755)
			_ = os.Symlink(filepath.Join(d, "user", "values.txt"), filepath.Join(d, "home", ".config", "core", "values.txt"))
		}},
		pcase{name: "blocked", config: "ok", steps: dryReal, prepare: func(d string) {
			write(filepath.Join(d, "home", ".config", "core"), header+"a file\n")
			_ = os.MkdirAll(filepath.Join(d, "home", ".config", "opt", "opt.txt"), 0o755)
		}},
	)
	return out
}

// env gives the environment of a run in the case folder <d>.
func env(d, fakeBin string, c pcase) []string {
	drop := map[string]bool{"HOME": true, "XDG_CACHE_HOME": true, "SYNC_ENGINE_CACHE": true, "MACOS_SETUP_CONFIG_PATH": true,
		"TMPDIR": true, "SYNC_ENGINE_VERBOSE": true, "PATH": true, "USER": true, "PWD": true, "FORCE_COLOR": true,
		"NO_COLOR": true, "TERM": true, "SYNC_ENGINE_CLONE": true, "MISE_DATA_DIR": true, "MISE_CACHE_DIR": true}
	var out []string
	for _, kv := range os.Environ() {
		k, _, _ := strings.Cut(kv, "=")
		if drop[k] || strings.HasPrefix(k, "GIT_") || strings.HasPrefix(k, "XDG_") {
			continue
		}
		out = append(out, kv)
	}
	home, _ := os.UserHomeDir()
	data := os.Getenv("MISE_DATA_DIR")
	if data == "" {
		data = filepath.Join(home, ".local", "share", "mise")
	}
	cache := os.Getenv("MISE_CACHE_DIR")
	if cache == "" {
		cache = filepath.Join(home, "Library", "Caches", "mise")
		if x := os.Getenv("XDG_CACHE_HOME"); x != "" {
			cache = filepath.Join(x, "mise")
		}
	}
	out = append(out,
		"HOME="+filepath.Join(d, "home"),
		"XDG_CACHE_HOME="+filepath.Join(d, "xdg", "cache"),
		"SYNC_ENGINE_CACHE="+filepath.Join(d, "xdg", "cache", "sync-engine"),
		"TMPDIR="+filepath.Join(d, "tmp"),
		"PATH="+fakeBin+":"+os.Getenv("PATH"),
		"USER=test", "PWD="+d, "TERM=dumb", "NO_COLOR=1",
		"MISE_DATA_DIR="+data, "MISE_CACHE_DIR="+cache,
		"GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1",
	)
	if c.config != "" {
		out = append(out, "MACOS_SETUP_CONFIG_PATH="+filepath.Join(d, "config"))
	} else {
		out = append(out, "MACOS_SETUP_CONFIG_PATH="+filepath.Join(d, "missing"))
	}
	if !c.quiet {
		out = append(out, "SYNC_ENGINE_VERBOSE=1")
	}
	return out
}

func copyDir(t *testing.T, from, to string) {
	t.Helper()
	if out, err := exec.Command("cp", "-R", from+"/.", to).CombinedOutput(); err != nil {
		t.Fatalf("cp %s: %v\n%s", from, err, out)
	}
}

// clone builds a clone copy in <dir>: sync-engine/ (the bash files) and the
// fixture repo as macos/, in a git repository.
func clone(t *testing.T, dir string, bad bool) {
	t.Helper()
	for _, d := range []string{"sync-engine", "macos"} {
		if err := os.MkdirAll(filepath.Join(dir, d), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	for _, name := range []string{"common", "write", "merge", "select", "manifest", "values", "mise", "setup-sync"} {
		b, err := os.ReadFile(filepath.Join(repoRoot, "sync-engine", name))
		if err != nil {
			t.Fatal(err)
		}
		write(filepath.Join(dir, "sync-engine", name), string(b))
	}
	copyDir(t, filepath.Join(repoRoot, "macos", "fixtures", "repo"), filepath.Join(dir, "macos"))
	if !bad {
		os.RemoveAll(filepath.Join(dir, "macos", "tools", "bad"))
	}
	git := func(args ...string) {
		cmd := exec.Command("git", append([]string{"-c", "user.name=test", "-c", "user.email=test@example.com",
			"-c", "commit.gpgsign=false", "-c", "core.hooksPath=/dev/null", "-c", "init.defaultBranch=main"}, args...)...)
		cmd.Dir = dir
		for _, kv := range os.Environ() {
			if !strings.HasPrefix(kv, "GIT_") {
				cmd.Env = append(cmd.Env, kv)
			}
		}
		cmd.Env = append(cmd.Env, "GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1")
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
	}
	git("init", "--quiet")
	git("add", "-A")
	git("commit", "--quiet", "--no-verify", "-m", "fixture")
}

// fakeMise makes <dir>/.local/bin/mise, which runs the real mise: the run
// needs a mise at ~/.local/bin/mise, and bash runs gomplate, jq and yq with it.
func fakeMise(t *testing.T, dir string) string {
	t.Helper()
	real, err := exec.LookPath("mise")
	if err != nil {
		t.Skip("no mise on PATH")
	}
	bin := filepath.Join(dir, ".local", "bin")
	write(filepath.Join(bin, "mise"), "#!/bin/sh\nexec '"+real+"' \"$@\"\n")
	if err := os.Chmod(filepath.Join(bin, "mise"), 0o755); err != nil {
		t.Fatal(err)
	}
	return bin
}

// setUp makes the case folder <d>.
func (c pcase) setUp(t *testing.T, d string) {
	t.Helper()
	for _, sub := range []string{"home", "xdg/cache", "tmp", "user"} {
		if err := os.MkdirAll(filepath.Join(d, sub), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	switch c.config {
	case "":
	case "-":
		_ = os.MkdirAll(filepath.Join(d, "config"), 0o755)
	default:
		_ = os.MkdirAll(filepath.Join(d, "config"), 0o755)
		copyDir(t, filepath.Join(repoRoot, "macos", "fixtures", "config", c.config), filepath.Join(d, "config"))
	}
	if c.prepare != nil {
		c.prepare(d)
	}
}

var (
	tempName = regexp.MustCompile(`(\.sync-engine|setup-sync|sync-engine-mise)\.[A-Za-z0-9]+`)
	gomplate = regexp.MustCompile(`(?m)^\{"time":.*\n`)
)

// normalize replaces the paths and the commit of a run.
func normalize(s, d, cloneDir, commit string) string {
	s = strings.ReplaceAll(s, d, "<case>")
	s = strings.ReplaceAll(s, cloneDir, "<clone>")
	if commit != "" {
		s = strings.ReplaceAll(s, commit, "<commit>")
		s = strings.ReplaceAll(s, commit[:7], "<short>")
	}
	s = gomplate.ReplaceAllString(s, "")
	s = tempName.ReplaceAllString(s, "$1.<tmp>")
	// No hook of the repository may change a golden file: a CR shows as
	// <CR>, a line with trailing whitespace gets a `$`, and the text ends
	// with a line of its own.
	s = strings.ReplaceAll(s, "\r", "<CR>")
	lines := strings.Split(s, "\n")
	for i, l := range lines {
		if strings.TrimRight(l, " \t") != l {
			lines[i] = l + "$"
		}
	}
	return strings.Join(lines, "\n") + "--- end\n"
}

// tree lists the files of the case folder: path, kind, mode and content. It
// leaves out the state of mise, which bash writes when it runs gomplate.
func tree(d string) string {
	var b strings.Builder
	var paths []string
	state := filepath.Join(d, "home", ".local")
	_ = filepath.WalkDir(d, func(p string, e fs.DirEntry, err error) error {
		if p == state {
			return filepath.SkipDir
		}
		if err == nil && p != d {
			paths = append(paths, p)
		}
		return nil
	})
	sort.Strings(paths)
	for _, p := range paths {
		rel, _ := filepath.Rel(d, p)
		info, err := os.Lstat(p)
		if err != nil {
			continue
		}
		switch {
		case info.Mode()&os.ModeSymlink != 0:
			l, _ := os.Readlink(p)
			fmt.Fprintf(&b, "link %s -> %s\n", rel, l)
		case info.IsDir():
			fmt.Fprintf(&b, "dir  %s %o\n", rel, info.Mode().Perm())
		default:
			data, _ := os.ReadFile(p)
			fmt.Fprintf(&b, "file %s %o\n", rel, info.Mode().Perm())
			for _, l := range strings.SplitAfter(string(data), "\n") {
				if l != "" {
					fmt.Fprintf(&b, "  | %s", strings.TrimSuffix(l, "\n"))
					if !strings.HasSuffix(l, "\n") {
						b.WriteString(" <no newline>")
					}
					b.WriteString("\n")
				}
			}
		}
	}
	return b.String()
}

// runCase runs the steps of <c> in the case folder <d> with <cmd> (the
// command and its leading arguments), and gives the normalized record.
func runCase(t *testing.T, c pcase, d, cloneDir, commit string, cmd []string) string {
	t.Helper()
	c.setUp(t, d)
	bin := fakeMise(t, d+".fake")
	var b strings.Builder
	for _, args := range c.steps {
		x := exec.Command(cmd[0], append(cmd[1:], args...)...)
		x.Dir = d
		x.Env = append(env(d, bin, c), "SYNC_ENGINE_CLONE="+cloneDir)
		var stdout, stderr strings.Builder
		x.Stdout, x.Stderr = &stdout, &stderr
		rc := 0
		if err := x.Run(); err != nil {
			ee, ok := err.(*exec.ExitError)
			if !ok {
				t.Fatalf("%s: %v", c.name, err)
			}
			rc = ee.ExitCode()
		}
		fmt.Fprintf(&b, "=== %s\nrc=%d\n--- stdout\n%s--- stderr\n%s--- files\n%s",
			strings.Join(args, " "), rc, stdout.String(), stderr.String(), tree(d))
	}
	return normalize(b.String(), d, cloneDir, commit)
}

// fingerprint is the hash of the inputs and of the bash files.
func fingerprint(t *testing.T) string {
	h := sha256.New()
	for _, name := range []string{"common", "write", "merge", "select", "manifest", "values", "mise", "setup-sync"} {
		b, _ := os.ReadFile(filepath.Join(repoRoot, "sync-engine", name))
		fmt.Fprintf(h, "%s %d\n", name, len(b))
		h.Write(b)
	}
	b, _ := os.ReadFile("parity_test.go")
	h.Write(b)
	_ = filepath.WalkDir(filepath.Join(repoRoot, "macos", "fixtures"), func(p string, e fs.DirEntry, err error) error {
		if err == nil && !e.IsDir() {
			b, _ := os.ReadFile(p)
			fmt.Fprintf(h, "%s %d\n", p, len(b))
			h.Write(b)
		}
		return nil
	})
	return hex.EncodeToString(h.Sum(nil))
}

func TestParity(t *testing.T) {
	bin := binary(t)
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	clones := map[bool]string{}
	commits := map[bool]string{}
	for _, bad := range []bool{false, true} {
		dir := filepath.Join(root, fmt.Sprintf("clone-%v", bad))
		clone(t, dir, bad)
		out, err := exec.Command("git", "-C", dir, "rev-parse", "HEAD").Output()
		if err != nil {
			t.Fatal(err)
		}
		clones[bad], commits[bad] = dir, strings.TrimSpace(string(out))
	}
	fp := fingerprint(t)
	live := os.Getenv("SYNC_ENGINE_LIVE") == "1"
	update := os.Getenv("UPDATE_GOLDEN") == "1"
	if (live || update) && !bashAvailable() {
		t.Fatal("SYNC_ENGINE_LIVE=1 and UPDATE_GOLDEN=1 need gomplate, jq and yq")
	}
	bashCmd := []string{"bash", "-c", `source "$SYNC_ENGINE_CLONE/sync-engine/setup-sync" && setup_sync "$@"`, "setup-sync"}
	for _, c := range cases(t) {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel()
			cl, commit := clones[c.bad], commits[c.bad]
			got := runCase(t, c, filepath.Join(root, "go", c.name), cl, commit, []string{bin, "macos"})
			golden := filepath.Join("testdata", "golden", c.name+".golden")
			var want string
			data, err := os.ReadFile(golden)
			head, rest, _ := strings.Cut(string(data), "\n")
			switch {
			case update || live || err != nil || head != "fingerprint: "+fp:
				if !bashAvailable() {
					t.Skipf("%s is missing or old, and bash cannot run here", golden)
				}
				want = runCase(t, c, filepath.Join(root, "bash", c.name), cl, commit, bashCmd)
				if update {
					write(golden, "fingerprint: "+fp+"\n"+want)
				}
			default:
				want = rest
			}
			if got != want {
				t.Errorf("Go differs from bash\n%s", diff(t, want, got))
			}
		})
	}
}

// diff gives `diff -u` of <want> (bash) and <got> (Go).
func diff(t *testing.T, want, got string) string {
	dir := t.TempDir()
	a, b := filepath.Join(dir, "bash"), filepath.Join(dir, "go")
	write(a, want)
	write(b, got)
	out, _ := exec.Command("diff", "-u", a, b).Output()
	return string(out)
}
