// example gives the values file of a repo example without its first lines
// of repo_name and repo_url.
func example(name string) string {
	b, err := os.ReadFile(filepath.Join(repoRoot, "repo", "examples", name, "bootstrap.toml"))
	if err != nil {
		return ""
	}
	var out []string
	for _, l := range strings.Split(string(b), "\n") {
		if strings.HasPrefix(l, "repo_name =") || strings.HasPrefix(l, "repo_url =") {
			continue
		}
		out = append(out, l)
	}
	return strings.Join(out, "\n")
}

// env gives the environment of a run in the case folder <d>.
func env(d string, c pcase, cloneDir string) []string {
	var out []string
	for _, kv := range os.Environ() {
		k, _, _ := strings.Cut(kv, "=")
		switch {
		case strings.HasPrefix(k, "GIT_"), strings.HasPrefix(k, "BOOTSTRAP_"), strings.HasPrefix(k, "REPO_SYNC_"):
			continue
		case k == "MISE_PROJECT_ROOT" || k == "TMPDIR" || k == "PWD" || k == "FORCE_COLOR" || k == "NO_COLOR" || k == "TERM":
			continue
		}
		out = append(out, kv)
	}
	repo := filepath.Join(d, "repo")
	out = append(out,
		"MISE_PROJECT_ROOT="+repo, "PWD="+repo, "TMPDIR="+filepath.Join(d, "tmp"),
		"TERM=dumb", "NO_COLOR=1", "REPO_SYNC_NO_AUTOUPDATE=1",
		"GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1",
	)
	if !c.noClone {
		out = append(out, "BOOTSTRAP_CLONE="+cloneDir)
	}
	if !c.quiet {
		out = append(out, "BOOTSTRAP_VERBOSE=1")
	}
	return out
}

// setUp makes the case folder <d>: the consumer repository with a `main`
// branch, and its values file.
func (c pcase) setUp(t *testing.T, d string) {
	t.Helper()
	repo := filepath.Join(d, "repo")
	for _, sub := range []string{"repo", "tmp"} {
		if err := os.MkdirAll(filepath.Join(d, sub), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	gitIn(t, repo, "init", "--quiet", "-b", "main")
	gitIn(t, repo, "commit", "--quiet", "--no-verify", "--allow-empty", "-m", "init")
	if c.values != "-" {
		write(filepath.Join(repo, ".config", "bootstrap.toml"), "repo_name = \"test\"\nrepo_url = \"https://example.com/test\"\n"+c.values)
	}
	if c.prepare != nil {
		c.prepare(t, repo)
	}
}

var (
	tempName = regexp.MustCompile(`(\.sync-engine|repo-sync|repo-sync-stage|repo-sync-ctx|sync-engine-mise)\.[A-Za-z0-9]+`)
	gomplate = regexp.MustCompile(`(?m)^\{"time":.*\n`)
)

// normalize replaces the paths and the commit of a run.
func normalize(s, d, cloneDir, commit string) string {
	s = strings.ReplaceAll(s, d, "<case>")
	s = strings.ReplaceAll(s, cloneDir, "<clone>")
	if commit != "" {
		s = strings.ReplaceAll(s, commit, "<commit>")
		s = strings.ReplaceAll(s, commit[:7], "<short>")
	}
	s = gomplate.ReplaceAllString(s, "")
	s = tempName.ReplaceAllString(s, "$1.<tmp>")
	// No hook of the repository may change a golden file: a CR shows as
	// <CR>, a line with trailing whitespace gets a `$`, and the text ends
	// with a line of its own.
	s = strings.ReplaceAll(s, "\r", "<CR>")
	lines := strings.Split(s, "\n")
	for i, l := range lines {
		if strings.TrimRight(l, " \t") != l {
			lines[i] = l + "$"
		}
	}
	return strings.Join(lines, "\n") + "--- end\n"
}

// tree lists the files of the case folder: path, kind, mode, size and a hash
// of the content, with the commit <commit> and the test folder replaced. It leaves out the .git
// folders. The dry runs show the
// content of each change in their diff.
func tree(d, commit string) string {
	var b strings.Builder
	var paths []string
	_ = filepath.WalkDir(d, func(p string, e fs.DirEntry, err error) error {
		if err == nil && e.IsDir() && e.Name() == ".git" {
			return filepath.SkipDir
		}
		if err == nil && p != d && e.Name() != ".git" {
			paths = append(paths, p)
		}
		return nil
	})
	sort.Strings(paths)
	for _, p := range paths {
		rel, _ := filepath.Rel(d, p)
		info, err := os.Lstat(p)
		if err != nil {
			continue
		}
		switch {
		case info.Mode()&os.ModeSymlink != 0:
			l, _ := os.Readlink(p)
			fmt.Fprintf(&b, "link %s -> %s\n", rel, l)
		case info.IsDir():
			fmt.Fprintf(&b, "dir  %s %o\n", rel, info.Mode().Perm())
		default:
			data, _ := os.ReadFile(p)
			// The commit of the clone and the temp folder of the test
			// change in each test run.
			data = []byte(strings.ReplaceAll(string(data), filepath.Dir(filepath.Dir(d)), "<root>"))
			if commit != "" {
				data = []byte(strings.ReplaceAll(string(data), commit, "<commit>"))
			}
			sum := sha256.Sum256(data)
			fmt.Fprintf(&b, "file %s %o %d %s\n", rel, info.Mode().Perm(), len(data), hex.EncodeToString(sum[:8]))
		}
	}
	return b.String()
}

// runCase runs the steps of <c> in the case folder <d> with <cmd> (the
// command and its leading arguments), and gives the normalized record.
func runCase(t *testing.T, c pcase, d, cloneDir, commit string, cmd []string) string {
	t.Helper()
	c.setUp(t, d)
	var b strings.Builder
	for _, args := range c.steps {
		x := exec.Command(cmd[0], append(cmd[1:], args...)...)
		x.Dir = filepath.Join(d, "repo")
		x.Env = env(d, c, cloneDir)
		var stdout, stderr strings.Builder
		x.Stdout, x.Stderr = &stdout, &stderr
		rc := 0
		if err := x.Run(); err != nil {
			ee, ok := err.(*exec.ExitError)
			if !ok {
				t.Fatalf("%s: %v", c.name, err)
			}
			rc = ee.ExitCode()
		}
		fmt.Fprintf(&b, "=== %s\nrc=%d\n--- stdout\n%s--- stderr\n%s--- files\n%s",
			strings.Join(args, " "), rc, stdout.String(), stderr.String(), tree(d, commit))
	}
	return normalize(b.String(), d, cloneDir, commit)
}

// fingerprint is the hash of the inputs: repo/ and tools/.
func fingerprint(t *testing.T) string {
	h := sha256.New()
	for _, dir := range []string{"repo", "tools"} {
		_ = filepath.WalkDir(filepath.Join(repoRoot, dir), func(p string, e fs.DirEntry, err error) error {
			if err == nil && !e.IsDir() {
				b, _ := os.ReadFile(p)
				fmt.Fprintf(h, "%s %d\n", p, len(b))
				h.Write(b)
			}
			return nil
		})
	}
	return hex.EncodeToString(h.Sum(nil))
}

func TestParity(t *testing.T) {
	if _, err := exec.LookPath("mise"); err != nil {
		t.Skip("no mise on PATH")
	}
	bin := binary(t)
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	cloneDir := filepath.Join(root, "clone")
	clone(t, cloneDir)
	out, err := exec.Command("git", "-C", cloneDir, "rev-parse", "HEAD").Output()
	if err != nil {
		t.Fatal(err)
	}
	commit := strings.TrimSpace(string(out))
	fp := fingerprint(t)
	for _, c := range cases() {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel()
			got := runCase(t, c, filepath.Join(root, "go", c.name), cloneDir, commit, []string{bin, "sync"})
			golden := filepath.Join("testdata", "golden", c.name+".golden")
			data, err := os.ReadFile(golden)
			head, want, _ := strings.Cut(string(data), "\n")
			if err != nil || head != "fingerprint: "+fp {
				t.Skipf("%s is missing or old (the inputs changed), and the bash engine that wrote it is gone", golden)
			}
			if got != want {
				t.Errorf("Go differs from bash\n%s", diff(t, want, got))
			}
		})
	}
}

// diff gives `diff -u` of <want> (bash) and <got> (Go).
func diff(t *testing.T, want, got string) string {
	dir := t.TempDir()
	a, b := filepath.Join(dir, "bash"), filepath.Join(dir, "go")
	write(a, want)
	write(b, got)
	out, _ := exec.Command("diff", "-u", a, b).Output()
	return string(out)
}
